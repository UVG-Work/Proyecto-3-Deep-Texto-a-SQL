-- Esquema de validación: gestión de conferencias y venta de entradas (nombres en inglés)

CREATE TABLE venue (
  venue_id INT PRIMARY KEY COMMENT 'Identificador del recinto',
  venue_name VARCHAR(80) NOT NULL COMMENT 'Nombre del recinto o centro de convenciones',
  city VARCHAR(40) NOT NULL COMMENT 'Ciudad del recinto',
  country VARCHAR(40) NOT NULL COMMENT 'País del recinto',
  capacity INT NOT NULL COMMENT 'Aforo máximo de personas'
) COMMENT='Recintos donde se realizan los eventos';

CREATE TABLE evt (
  evt_id INT PRIMARY KEY COMMENT 'Identificador del evento',
  title VARCHAR(100) NOT NULL COMMENT 'Nombre del evento o conferencia',
  venue_id INT NOT NULL COMMENT 'Recinto donde se realiza',
  cat VARCHAR(30) NOT NULL COMMENT 'Categoría temática del evento',
  start_dt DATE NOT NULL COMMENT 'Fecha de inicio del evento',
  end_dt DATE NOT NULL COMMENT 'Fecha de fin del evento',
  base_price DECIMAL(8,2) NOT NULL COMMENT 'Precio base de la entrada general en USD',
  status VARCHAR(12) NOT NULL COMMENT 'Estado: scheduled (programado), completed (realizado), cancelled (cancelado)',
  FOREIGN KEY (venue_id) REFERENCES venue(venue_id)
) COMMENT='Eventos y conferencias organizados';

CREATE TABLE speaker (
  spk_id INT PRIMARY KEY COMMENT 'Identificador del ponente',
  full_name VARCHAR(80) NOT NULL COMMENT 'Nombre completo del ponente',
  company VARCHAR(60) COMMENT 'Empresa u organización a la que pertenece (puede ser nula)',
  country VARCHAR(40) NOT NULL COMMENT 'País de origen del ponente',
  email VARCHAR(80) COMMENT 'Correo electrónico del ponente'
) COMMENT='Ponentes o expositores';

CREATE TABLE session (
  session_id INT PRIMARY KEY COMMENT 'Identificador de la sesión',
  evt_id INT NOT NULL COMMENT 'Evento al que pertenece la sesión',
  spk_id INT COMMENT 'Ponente a cargo (nulo si aún no está asignado)',
  title VARCHAR(120) NOT NULL COMMENT 'Título de la charla o taller',
  sess_type VARCHAR(15) NOT NULL COMMENT 'Tipo de sesión: keynote, talk, workshop, panel',
  start_ts DATETIME NOT NULL COMMENT 'Fecha y hora de inicio de la sesión',
  dur_min INT NOT NULL COMMENT 'Duración en minutos',
  room VARCHAR(20) NOT NULL COMMENT 'Sala donde se dicta',
  FOREIGN KEY (evt_id) REFERENCES evt(evt_id),
  FOREIGN KEY (spk_id) REFERENCES speaker(spk_id)
) COMMENT='Sesiones (charlas, talleres, paneles) de cada evento';

CREATE TABLE attendee (
  att_id INT PRIMARY KEY COMMENT 'Identificador del asistente',
  first_name VARCHAR(40) NOT NULL COMMENT 'Nombre del asistente',
  last_name VARCHAR(40) NOT NULL COMMENT 'Apellido del asistente',
  email VARCHAR(80) NOT NULL UNIQUE COMMENT 'Correo electrónico del asistente',
  country VARCHAR(40) NOT NULL COMMENT 'País de residencia',
  reg_dt DATE NOT NULL COMMENT 'Fecha de registro en la plataforma'
) COMMENT='Asistentes registrados en la plataforma de venta';

CREATE TABLE ticket (
  ticket_id INT PRIMARY KEY COMMENT 'Identificador de la entrada',
  evt_id INT NOT NULL COMMENT 'Evento para el que se compró la entrada',
  att_id INT NOT NULL COMMENT 'Asistente que compró la entrada',
  tkt_type VARCHAR(10) NOT NULL COMMENT 'Tipo de entrada: General, VIP, Student',
  price_paid DECIMAL(8,2) NOT NULL COMMENT 'Monto pagado en USD tras descuentos',
  purchase_ts DATETIME NOT NULL COMMENT 'Fecha y hora de la compra',
  disc_code VARCHAR(15) COMMENT 'Código de descuento aplicado (nulo si no se usó)',
  status VARCHAR(10) NOT NULL COMMENT 'Estado: paid (pagada) o refunded (reembolsada)',
  FOREIGN KEY (evt_id) REFERENCES evt(evt_id),
  FOREIGN KEY (att_id) REFERENCES attendee(att_id)
) COMMENT='Entradas vendidas';

CREATE TABLE sponsor (
  sponsor_id INT PRIMARY KEY COMMENT 'Identificador del patrocinador',
  sponsor_name VARCHAR(80) NOT NULL COMMENT 'Nombre del patrocinador',
  industry VARCHAR(40) NOT NULL COMMENT 'Sector o industria del patrocinador'
) COMMENT='Empresas patrocinadoras';

CREATE TABLE evt_sponsor (
  evt_id INT NOT NULL COMMENT 'Evento patrocinado',
  sponsor_id INT NOT NULL COMMENT 'Patrocinador',
  tier VARCHAR(10) NOT NULL COMMENT 'Nivel de patrocinio: Gold, Silver, Bronze',
  amount DECIMAL(10,2) NOT NULL COMMENT 'Monto aportado en USD',
  PRIMARY KEY (evt_id, sponsor_id),
  FOREIGN KEY (evt_id) REFERENCES evt(evt_id),
  FOREIGN KEY (sponsor_id) REFERENCES sponsor(sponsor_id)
) COMMENT='Patrocinios de cada evento';

