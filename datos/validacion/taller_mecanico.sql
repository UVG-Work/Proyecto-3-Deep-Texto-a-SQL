-- Esquema de validación: taller mecánico (nombres en español abreviado)

CREATE TABLE cli (
  id_cli INT PRIMARY KEY COMMENT 'Identificador del cliente',
  nom VARCHAR(50) NOT NULL COMMENT 'Nombre del cliente',
  ape VARCHAR(50) NOT NULL COMMENT 'Apellido del cliente',
  tel VARCHAR(15) COMMENT 'Teléfono de contacto',
  email VARCHAR(80) COMMENT 'Correo electrónico (puede ser nulo)',
  ciu VARCHAR(40) NOT NULL COMMENT 'Ciudad de residencia',
  f_reg DATE NOT NULL COMMENT 'Fecha de registro del cliente en el taller'
) COMMENT='Clientes del taller';

CREATE TABLE veh (
  id_veh INT PRIMARY KEY COMMENT 'Identificador del vehículo',
  placa VARCHAR(10) NOT NULL UNIQUE COMMENT 'Placa del vehículo',
  marca VARCHAR(30) NOT NULL COMMENT 'Marca del vehículo',
  modelo VARCHAR(40) NOT NULL COMMENT 'Modelo del vehículo',
  anio SMALLINT NOT NULL COMMENT 'Año de fabricación',
  comb VARCHAR(15) NOT NULL COMMENT 'Tipo de combustible: Gasolina, Diésel, Híbrido, GLP',
  id_cli INT NOT NULL COMMENT 'Cliente propietario',
  FOREIGN KEY (id_cli) REFERENCES cli(id_cli)
) COMMENT='Vehículos registrados de los clientes';

CREATE TABLE mec (
  id_mec INT PRIMARY KEY COMMENT 'Identificador del mecánico',
  nom VARCHAR(50) NOT NULL COMMENT 'Nombre del mecánico',
  ape VARCHAR(50) NOT NULL COMMENT 'Apellido del mecánico',
  espec VARCHAR(30) NOT NULL COMMENT 'Especialidad del mecánico',
  f_contr DATE NOT NULL COMMENT 'Fecha de contratación',
  tarifa_h DECIMAL(8,2) NOT NULL COMMENT 'Tarifa por hora de mano de obra'
) COMMENT='Mecánicos del taller';

CREATE TABLE srv (
  id_srv INT PRIMARY KEY COMMENT 'Identificador del servicio',
  desc_srv VARCHAR(60) NOT NULL COMMENT 'Descripción del servicio',
  cat VARCHAR(30) NOT NULL COMMENT 'Categoría del servicio',
  precio_ref DECIMAL(8,2) NOT NULL COMMENT 'Precio de referencia del servicio',
  hrs_est DECIMAL(4,1) NOT NULL COMMENT 'Horas estimadas de trabajo'
) COMMENT='Catálogo de servicios ofrecidos';

CREATE TABLE prov (
  id_prov INT PRIMARY KEY COMMENT 'Identificador del proveedor',
  razon_soc VARCHAR(80) NOT NULL COMMENT 'Razón social del proveedor',
  ciu VARCHAR(40) NOT NULL COMMENT 'Ciudad del proveedor',
  tel VARCHAR(15) COMMENT 'Teléfono del proveedor'
) COMMENT='Proveedores de repuestos';

CREATE TABLE rep (
  id_rep INT PRIMARY KEY COMMENT 'Identificador del repuesto',
  cod_rep VARCHAR(15) NOT NULL UNIQUE COMMENT 'Código interno del repuesto',
  desc_rep VARCHAR(60) NOT NULL COMMENT 'Descripción del repuesto',
  precio_u DECIMAL(8,2) NOT NULL COMMENT 'Precio unitario de venta',
  stock INT NOT NULL COMMENT 'Unidades en almacén',
  id_prov INT COMMENT 'Proveedor habitual (puede ser nulo)',
  FOREIGN KEY (id_prov) REFERENCES prov(id_prov)
) COMMENT='Repuestos en inventario del taller';

CREATE TABLE ord_srv (
  id_ord INT PRIMARY KEY COMMENT 'Número de la orden de servicio',
  id_veh INT NOT NULL COMMENT 'Vehículo atendido',
  id_mec INT NOT NULL COMMENT 'Mecánico responsable',
  id_srv INT NOT NULL COMMENT 'Servicio principal realizado',
  f_ing DATE NOT NULL COMMENT 'Fecha de ingreso del vehículo al taller',
  f_ent DATE COMMENT 'Fecha de entrega al cliente (nula si aún no se entrega)',
  km INT NOT NULL COMMENT 'Kilometraje del vehículo al ingresar',
  costo_mo DECIMAL(10,2) NOT NULL COMMENT 'Costo de mano de obra cobrado',
  est VARCHAR(15) NOT NULL COMMENT 'Estado de la orden: Pendiente, En proceso, Entregada, Cancelada',
  FOREIGN KEY (id_veh) REFERENCES veh(id_veh),
  FOREIGN KEY (id_mec) REFERENCES mec(id_mec),
  FOREIGN KEY (id_srv) REFERENCES srv(id_srv)
) COMMENT='Órdenes de servicio (cada ingreso de un vehículo al taller)';

CREATE TABLE det_ord (
  id_det INT PRIMARY KEY COMMENT 'Identificador de la línea de detalle',
  id_ord INT NOT NULL COMMENT 'Orden de servicio',
  id_rep INT NOT NULL COMMENT 'Repuesto utilizado',
  cant INT NOT NULL COMMENT 'Cantidad de unidades usadas',
  p_unit DECIMAL(8,2) NOT NULL COMMENT 'Precio unitario cobrado en la orden',
  FOREIGN KEY (id_ord) REFERENCES ord_srv(id_ord),
  FOREIGN KEY (id_rep) REFERENCES rep(id_rep)
) COMMENT='Repuestos utilizados en cada orden de servicio';

