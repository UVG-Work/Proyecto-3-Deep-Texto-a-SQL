-- Esquema hotel: hoteles, habitaciones, huéspedes, reservas, pagos y servicios

CREATE TABLE htl (
  htl_id INT NOT NULL COMMENT 'Identificador del hotel',
  htl_nm VARCHAR(60) NOT NULL COMMENT 'Nombre del hotel',
  city VARCHAR(40) NOT NULL COMMENT 'Ciudad donde está el hotel',
  ctry VARCHAR(30) NOT NULL COMMENT 'País donde está el hotel',
  stars TINYINT NOT NULL COMMENT 'Categoría del hotel en estrellas (1 a 5)',
  opn_dt DATE NOT NULL COMMENT 'Fecha de apertura del hotel',
  PRIMARY KEY (htl_id)
) COMMENT='Hoteles de la cadena';

CREATE TABLE rm_type (
  rt_id INT NOT NULL COMMENT 'Identificador del tipo de habitación',
  rt_nm VARCHAR(30) NOT NULL COMMENT 'Nombre del tipo de habitación',
  max_occ TINYINT NOT NULL COMMENT 'Ocupación máxima (número de personas)',
  bed_cfg VARCHAR(40) NOT NULL COMMENT 'Configuración de camas',
  PRIMARY KEY (rt_id)
) COMMENT='Tipos de habitación';

CREATE TABLE rm (
  rm_id INT NOT NULL COMMENT 'Identificador de la habitación',
  htl_id INT NOT NULL COMMENT 'Hotel al que pertenece la habitación',
  rt_id INT NOT NULL COMMENT 'Tipo de habitación',
  rm_no VARCHAR(6) NOT NULL COMMENT 'Número de la habitación dentro del hotel',
  flr TINYINT NOT NULL COMMENT 'Piso en que se ubica la habitación',
  nt_rate DECIMAL(10,2) NOT NULL COMMENT 'Tarifa por noche en dólares',
  is_actv TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1 = habitación habilitada, 0 = fuera de servicio',
  PRIMARY KEY (rm_id),
  FOREIGN KEY (htl_id) REFERENCES htl(htl_id),
  FOREIGN KEY (rt_id) REFERENCES rm_type(rt_id)
) COMMENT='Habitaciones de cada hotel';

CREATE TABLE gst (
  gst_id INT NOT NULL COMMENT 'Identificador del huésped',
  f_nm VARCHAR(40) NOT NULL COMMENT 'Nombre del huésped',
  l_nm VARCHAR(40) NOT NULL COMMENT 'Apellido del huésped',
  email VARCHAR(80) NULL COMMENT 'Correo electrónico',
  phn VARCHAR(20) NULL COMMENT 'Teléfono',
  ctry VARCHAR(30) NOT NULL COMMENT 'País de residencia del huésped',
  birth_dt DATE NULL COMMENT 'Fecha de nacimiento',
  vip_flg TINYINT(1) NOT NULL DEFAULT 0 COMMENT '1 = cliente VIP, 0 = cliente normal',
  PRIMARY KEY (gst_id)
) COMMENT='Huéspedes (clientes)';

CREATE TABLE rsv (
  rsv_id INT NOT NULL COMMENT 'Identificador de la reserva',
  gst_id INT NOT NULL COMMENT 'Huésped titular de la reserva',
  rm_id INT NOT NULL COMMENT 'Habitación reservada',
  bkd_at DATETIME NOT NULL COMMENT 'Fecha y hora en que se hizo la reserva',
  chk_in DATE NOT NULL COMMENT 'Fecha de llegada (check-in)',
  chk_out DATE NOT NULL COMMENT 'Fecha de salida (check-out)',
  gst_cnt TINYINT NOT NULL COMMENT 'Cantidad de huéspedes en la habitación',
  sts VARCHAR(4) NOT NULL COMMENT 'Estado: CONF=confirmada, DONE=finalizada, CANC=cancelada, NOSH=no se presentó',
  chnl VARCHAR(6) NOT NULL COMMENT 'Canal de venta: WEB, PHONE, OTA (agencia en línea) o WALKIN (en recepción)',
  tot_amt DECIMAL(10,2) NOT NULL COMMENT 'Monto total del alojamiento (noches por tarifa) en dólares',
  PRIMARY KEY (rsv_id),
  FOREIGN KEY (gst_id) REFERENCES gst(gst_id),
  FOREIGN KEY (rm_id) REFERENCES rm(rm_id)
) COMMENT='Reservas de habitaciones';

CREATE TABLE pmt (
  pmt_id INT NOT NULL COMMENT 'Identificador del pago',
  rsv_id INT NOT NULL COMMENT 'Reserva que se paga',
  pmt_dt DATETIME NOT NULL COMMENT 'Fecha y hora del pago',
  amt DECIMAL(10,2) NOT NULL COMMENT 'Monto pagado en dólares',
  mthd VARCHAR(8) NOT NULL COMMENT 'Medio de pago: CARD (tarjeta), CASH (efectivo) o TRANSFER (transferencia)',
  PRIMARY KEY (pmt_id),
  FOREIGN KEY (rsv_id) REFERENCES rsv(rsv_id)
) COMMENT='Pagos asociados a reservas';

CREATE TABLE svc (
  svc_id INT NOT NULL COMMENT 'Identificador del servicio',
  svc_nm VARCHAR(40) NOT NULL COMMENT 'Nombre del servicio adicional',
  ctg VARCHAR(20) NOT NULL COMMENT 'Categoría del servicio',
  unit_prc DECIMAL(8,2) NOT NULL COMMENT 'Precio unitario del servicio en dólares',
  PRIMARY KEY (svc_id)
) COMMENT='Servicios adicionales ofrecidos';

CREATE TABLE rsv_svc (
  rs_id INT NOT NULL COMMENT 'Identificador del consumo',
  rsv_id INT NOT NULL COMMENT 'Reserva a la que se carga el servicio',
  svc_id INT NOT NULL COMMENT 'Servicio consumido',
  qty INT NOT NULL COMMENT 'Cantidad consumida',
  svc_dt DATE NOT NULL COMMENT 'Fecha del consumo',
  PRIMARY KEY (rs_id),
  FOREIGN KEY (rsv_id) REFERENCES rsv(rsv_id),
  FOREIGN KEY (svc_id) REFERENCES svc(svc_id)
) COMMENT='Servicios consumidos durante las reservas';

