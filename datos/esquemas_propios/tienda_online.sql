-- Esquema tienda_online: comercio electrónico con nombres en español abreviado

CREATE TABLE cat (
  id_cat INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador de la categoría',
  nom VARCHAR(60) NOT NULL COMMENT 'Nombre de la categoría',
  descr VARCHAR(200) NULL COMMENT 'Descripción de la categoría',
  PRIMARY KEY (id_cat)
) COMMENT='Categorías de productos';

CREATE TABLE prod (
  id_prod INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador del producto',
  nom VARCHAR(100) NOT NULL COMMENT 'Nombre del producto',
  id_cat INT NOT NULL COMMENT 'Categoría a la que pertenece el producto',
  precio_u DECIMAL(10,2) NOT NULL COMMENT 'Precio unitario de venta actual en euros',
  stock INT NOT NULL DEFAULT 0 COMMENT 'Unidades disponibles en almacén',
  f_alta DATE NOT NULL COMMENT 'Fecha en que el producto se dio de alta en el catálogo',
  activo TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1 = producto a la venta, 0 = descatalogado',
  PRIMARY KEY (id_prod),
  CONSTRAINT fk_prod_cat FOREIGN KEY (id_cat) REFERENCES cat (id_cat)
) COMMENT='Productos del catálogo';

CREATE TABLE cli (
  id_cli INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador del cliente',
  nom VARCHAR(50) NOT NULL COMMENT 'Nombre de pila del cliente',
  ape VARCHAR(60) NOT NULL COMMENT 'Apellido del cliente',
  email VARCHAR(120) NOT NULL COMMENT 'Correo electrónico',
  ciudad VARCHAR(60) NOT NULL COMMENT 'Ciudad de residencia',
  f_alta DATE NOT NULL COMMENT 'Fecha de registro del cliente en la tienda',
  f_nac DATE NULL COMMENT 'Fecha de nacimiento (opcional)',
  tel VARCHAR(15) NULL COMMENT 'Teléfono de contacto (opcional)',
  PRIMARY KEY (id_cli),
  UNIQUE KEY uq_cli_email (email)
) COMMENT='Clientes registrados';

CREATE TABLE ped (
  id_ped INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador del pedido',
  id_cli INT NOT NULL COMMENT 'Cliente que realizó el pedido',
  f_ped DATETIME NOT NULL COMMENT 'Fecha y hora del pedido',
  estado VARCHAR(20) NOT NULL COMMENT 'Estado del pedido: pendiente, enviado, entregado o cancelado',
  dir_env VARCHAR(150) NOT NULL COMMENT 'Dirección de envío',
  f_entrega DATE NULL COMMENT 'Fecha de entrega (NULL si aún no se ha entregado)',
  PRIMARY KEY (id_ped),
  CONSTRAINT fk_ped_cli FOREIGN KEY (id_cli) REFERENCES cli (id_cli)
) COMMENT='Pedidos de los clientes';

CREATE TABLE det_ped (
  id_det INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador de la línea de pedido',
  id_ped INT NOT NULL COMMENT 'Pedido al que pertenece la línea',
  id_prod INT NOT NULL COMMENT 'Producto comprado',
  cant INT NOT NULL COMMENT 'Cantidad de unidades compradas',
  precio_u DECIMAL(10,2) NOT NULL COMMENT 'Precio unitario aplicado en el momento de la compra',
  dscto DECIMAL(5,2) NOT NULL DEFAULT 0 COMMENT 'Porcentaje de descuento aplicado a la línea (0-100)',
  PRIMARY KEY (id_det),
  CONSTRAINT fk_det_ped FOREIGN KEY (id_ped) REFERENCES ped (id_ped),
  CONSTRAINT fk_det_prod FOREIGN KEY (id_prod) REFERENCES prod (id_prod)
) COMMENT='Detalle (líneas) de cada pedido';

CREATE TABLE pago (
  id_pago INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador del pago',
  id_ped INT NOT NULL COMMENT 'Pedido que se paga',
  f_pago DATETIME NOT NULL COMMENT 'Fecha y hora del pago',
  monto DECIMAL(10,2) NOT NULL COMMENT 'Importe pagado en euros',
  metodo VARCHAR(20) NOT NULL COMMENT 'Método de pago: tarjeta, paypal, transferencia o bizum',
  PRIMARY KEY (id_pago),
  CONSTRAINT fk_pago_ped FOREIGN KEY (id_ped) REFERENCES ped (id_ped)
) COMMENT='Pagos recibidos (un pedido puede pagarse en varios plazos)';

CREATE TABLE resena (
  id_res INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador de la reseña',
  id_prod INT NOT NULL COMMENT 'Producto reseñado',
  id_cli INT NOT NULL COMMENT 'Cliente autor de la reseña',
  punt TINYINT NOT NULL COMMENT 'Puntuación de 1 a 5 estrellas',
  coment VARCHAR(300) NULL COMMENT 'Comentario opcional',
  f_res DATE NOT NULL COMMENT 'Fecha de la reseña',
  PRIMARY KEY (id_res),
  CONSTRAINT fk_res_prod FOREIGN KEY (id_prod) REFERENCES prod (id_prod),
  CONSTRAINT fk_res_cli FOREIGN KEY (id_cli) REFERENCES cli (id_cli)
) COMMENT='Reseñas de productos escritas por clientes';

