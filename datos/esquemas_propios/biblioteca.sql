-- Esquema biblioteca: red de bibliotecas con nombres en inglés abreviado

CREATE TABLE brch (
  brch_id INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador de la sucursal (branch)',
  nm VARCHAR(80) NOT NULL COMMENT 'Nombre de la sucursal',
  cty VARCHAR(60) NOT NULL COMMENT 'Ciudad donde está la sucursal',
  opn_dt DATE NOT NULL COMMENT 'Fecha de inauguración',
  PRIMARY KEY (brch_id)
) COMMENT='Sucursales de la red de bibliotecas';

CREATE TABLE auth (
  auth_id INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador del autor',
  fnm VARCHAR(50) NOT NULL COMMENT 'Nombre de pila del autor (first name)',
  lnm VARCHAR(60) NOT NULL COMMENT 'Apellido(s) del autor (last name)',
  ntn VARCHAR(40) NOT NULL COMMENT 'País de nacionalidad del autor',
  brth_yr SMALLINT NULL COMMENT 'Año de nacimiento (NULL si se desconoce)',
  PRIMARY KEY (auth_id)
) COMMENT='Autores';

CREATE TABLE bk (
  bk_id INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador del libro (obra)',
  ttl VARCHAR(150) NOT NULL COMMENT 'Título del libro',
  auth_id INT NULL COMMENT 'Autor del libro (NULL si no está registrado)',
  gnr VARCHAR(40) NOT NULL COMMENT 'Género literario (Novela, Misterio, Ensayo, Cuento, Clásico, Ciencia ficción, Biografía, Novela histórica)',
  pub_yr SMALLINT NOT NULL COMMENT 'Año de publicación original',
  isbn VARCHAR(20) NULL COMMENT 'Código ISBN (NULL en ediciones antiguas)',
  pg_cnt INT NOT NULL COMMENT 'Número de páginas',
  rpl_prc DECIMAL(6,2) NOT NULL COMMENT 'Precio de reposición en euros si se pierde un ejemplar',
  PRIMARY KEY (bk_id),
  CONSTRAINT fk_bk_auth FOREIGN KEY (auth_id) REFERENCES auth (auth_id)
) COMMENT='Libros (obras) del catálogo';

CREATE TABLE cpy (
  cpy_id INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador del ejemplar físico (copy)',
  bk_id INT NOT NULL COMMENT 'Libro al que corresponde el ejemplar',
  brch_id INT NOT NULL COMMENT 'Sucursal donde se encuentra el ejemplar',
  acq_dt DATE NOT NULL COMMENT 'Fecha de adquisición del ejemplar',
  cond VARCHAR(10) NOT NULL COMMENT 'Estado de conservación: nuevo, bueno o gastado',
  PRIMARY KEY (cpy_id),
  CONSTRAINT fk_cpy_bk FOREIGN KEY (bk_id) REFERENCES bk (bk_id),
  CONSTRAINT fk_cpy_brch FOREIGN KEY (brch_id) REFERENCES brch (brch_id)
) COMMENT='Ejemplares físicos de cada libro en cada sucursal';

CREATE TABLE mbr (
  mbr_id INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador del socio (member)',
  fnm VARCHAR(50) NOT NULL COMMENT 'Nombre del socio',
  lnm VARCHAR(60) NOT NULL COMMENT 'Apellido del socio',
  eml VARCHAR(120) NULL COMMENT 'Correo electrónico (opcional)',
  jn_dt DATE NOT NULL COMMENT 'Fecha de alta como socio (join date)',
  mbr_tp VARCHAR(12) NOT NULL COMMENT 'Tipo de socio: estandar, premium o estudiante',
  brch_id INT NOT NULL COMMENT 'Sucursal de inscripción del socio',
  PRIMARY KEY (mbr_id),
  CONSTRAINT fk_mbr_brch FOREIGN KEY (brch_id) REFERENCES brch (brch_id)
) COMMENT='Socios de la biblioteca';

CREATE TABLE ln (
  ln_id INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador del préstamo (loan)',
  cpy_id INT NOT NULL COMMENT 'Ejemplar prestado',
  mbr_id INT NOT NULL COMMENT 'Socio que toma el préstamo',
  ln_dt DATE NOT NULL COMMENT 'Fecha del préstamo',
  due_dt DATE NOT NULL COMMENT 'Fecha límite de devolución',
  ret_dt DATE NULL COMMENT 'Fecha real de devolución (NULL si no se ha devuelto)',
  PRIMARY KEY (ln_id),
  CONSTRAINT fk_ln_cpy FOREIGN KEY (cpy_id) REFERENCES cpy (cpy_id),
  CONSTRAINT fk_ln_mbr FOREIGN KEY (mbr_id) REFERENCES mbr (mbr_id)
) COMMENT='Préstamos de ejemplares a socios';

CREATE TABLE fn (
  fn_id INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador de la multa (fine)',
  ln_id INT NOT NULL COMMENT 'Préstamo que generó la multa',
  amt DECIMAL(6,2) NOT NULL COMMENT 'Importe de la multa en euros',
  pd_dt DATE NULL COMMENT 'Fecha de pago de la multa (NULL si está pendiente)',
  PRIMARY KEY (fn_id),
  CONSTRAINT fk_fn_ln FOREIGN KEY (ln_id) REFERENCES ln (ln_id)
) COMMENT='Multas por devolución tardía o pérdida';

