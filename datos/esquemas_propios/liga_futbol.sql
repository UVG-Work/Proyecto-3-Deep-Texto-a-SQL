-- Esquema liga_futbol: temporadas, estadios, equipos, jugadores, partidos, goles y tarjetas

CREATE TABLE temporadas (
  id_temporada INT NOT NULL COMMENT 'Identificador de la temporada',
  nombre VARCHAR(30) NOT NULL COMMENT 'Nombre de la temporada',
  anio INT NOT NULL COMMENT 'Año en que se disputa la temporada',
  fecha_inicio DATE NOT NULL COMMENT 'Fecha de inicio de la temporada',
  fecha_fin DATE NOT NULL COMMENT 'Fecha de término de la temporada',
  PRIMARY KEY (id_temporada)
) COMMENT='Temporadas de la liga';

CREATE TABLE estadios (
  id_estadio INT NOT NULL COMMENT 'Identificador del estadio',
  nombre VARCHAR(60) NOT NULL COMMENT 'Nombre del estadio',
  ciudad VARCHAR(40) NOT NULL COMMENT 'Ciudad donde se ubica el estadio',
  capacidad INT NOT NULL COMMENT 'Capacidad máxima de espectadores',
  anio_inauguracion INT NULL COMMENT 'Año de inauguración del estadio',
  PRIMARY KEY (id_estadio)
) COMMENT='Estadios donde se juegan los partidos';

CREATE TABLE equipos (
  id_equipo INT NOT NULL COMMENT 'Identificador del equipo',
  nombre VARCHAR(60) NOT NULL COMMENT 'Nombre del club',
  ciudad VARCHAR(40) NOT NULL COMMENT 'Ciudad de origen del club',
  id_estadio INT NOT NULL COMMENT 'Estadio donde juega como local',
  anio_fundacion INT NOT NULL COMMENT 'Año de fundación del club',
  entrenador VARCHAR(60) NULL COMMENT 'Nombre del entrenador actual (NULL si está vacante)',
  presupuesto_anual DECIMAL(12,2) NOT NULL COMMENT 'Presupuesto anual del club en dólares',
  PRIMARY KEY (id_equipo),
  FOREIGN KEY (id_estadio) REFERENCES estadios(id_estadio)
) COMMENT='Equipos que participan en la liga';

CREATE TABLE jugadores (
  id_jugador INT NOT NULL COMMENT 'Identificador del jugador',
  nombre VARCHAR(40) NOT NULL COMMENT 'Nombre de pila del jugador',
  apellido VARCHAR(40) NOT NULL COMMENT 'Apellido del jugador',
  fecha_nacimiento DATE NOT NULL COMMENT 'Fecha de nacimiento',
  nacionalidad VARCHAR(30) NOT NULL COMMENT 'Nacionalidad del jugador',
  posicion VARCHAR(15) NOT NULL COMMENT 'Posición: Portero, Defensa, Mediocampista o Delantero',
  id_equipo INT NULL COMMENT 'Equipo actual (NULL si es agente libre)',
  dorsal INT NULL COMMENT 'Número de camiseta',
  salario_mensual DECIMAL(10,2) NULL COMMENT 'Salario mensual en dólares',
  altura_cm INT NULL COMMENT 'Estatura en centímetros',
  PRIMARY KEY (id_jugador),
  FOREIGN KEY (id_equipo) REFERENCES equipos(id_equipo)
) COMMENT='Jugadores registrados en la liga';

CREATE TABLE partidos (
  id_partido INT NOT NULL COMMENT 'Identificador del partido',
  id_temporada INT NOT NULL COMMENT 'Temporada a la que pertenece el partido',
  jornada INT NOT NULL COMMENT 'Número de jornada (fecha del campeonato)',
  fecha DATETIME NOT NULL COMMENT 'Fecha y hora de inicio del partido',
  id_equipo_local INT NOT NULL COMMENT 'Equipo que juega de local',
  id_equipo_visitante INT NOT NULL COMMENT 'Equipo que juega de visitante',
  id_estadio INT NOT NULL COMMENT 'Estadio donde se jugó',
  goles_local INT NOT NULL COMMENT 'Goles anotados por el equipo local',
  goles_visitante INT NOT NULL COMMENT 'Goles anotados por el equipo visitante',
  asistencia INT NULL COMMENT 'Número de espectadores (NULL si no se informó)',
  arbitro VARCHAR(60) NOT NULL COMMENT 'Nombre del árbitro principal',
  PRIMARY KEY (id_partido),
  FOREIGN KEY (id_temporada) REFERENCES temporadas(id_temporada),
  FOREIGN KEY (id_equipo_local) REFERENCES equipos(id_equipo),
  FOREIGN KEY (id_equipo_visitante) REFERENCES equipos(id_equipo),
  FOREIGN KEY (id_estadio) REFERENCES estadios(id_estadio)
) COMMENT='Partidos disputados';

CREATE TABLE goles (
  id_gol INT NOT NULL COMMENT 'Identificador del gol',
  id_partido INT NOT NULL COMMENT 'Partido en que se anotó',
  id_jugador INT NOT NULL COMMENT 'Jugador que anotó el gol',
  minuto INT NOT NULL COMMENT 'Minuto del partido en que se anotó',
  tipo VARCHAR(15) NOT NULL COMMENT 'Tipo de gol: Jugada, Cabezazo, Penal o Tiro libre',
  PRIMARY KEY (id_gol),
  FOREIGN KEY (id_partido) REFERENCES partidos(id_partido),
  FOREIGN KEY (id_jugador) REFERENCES jugadores(id_jugador)
) COMMENT='Goles anotados en los partidos';

CREATE TABLE tarjetas (
  id_tarjeta INT NOT NULL COMMENT 'Identificador de la tarjeta',
  id_partido INT NOT NULL COMMENT 'Partido en que se mostró',
  id_jugador INT NOT NULL COMMENT 'Jugador amonestado o expulsado',
  minuto INT NOT NULL COMMENT 'Minuto en que se mostró la tarjeta',
  color VARCHAR(10) NOT NULL COMMENT 'Color de la tarjeta: Amarilla o Roja',
  PRIMARY KEY (id_tarjeta),
  FOREIGN KEY (id_partido) REFERENCES partidos(id_partido),
  FOREIGN KEY (id_jugador) REFERENCES jugadores(id_jugador)
) COMMENT='Tarjetas amarillas y rojas mostradas';

