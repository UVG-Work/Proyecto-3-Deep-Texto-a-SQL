CREATE TABLE comunas (
  comuna_id INT PRIMARY KEY COMMENT 'Identificador de la comuna',
  nombre VARCHAR(60) NOT NULL COMMENT 'Nombre de la comuna',
  region VARCHAR(40) NOT NULL COMMENT 'Región: Metropolitana, Valparaíso, Biobío',
  valor_m2_referencia DECIMAL(10,2) COMMENT 'Valor de referencia del metro cuadrado en la comuna (CLP)'
) COMMENT='Comunas donde opera la agencia';

CREATE TABLE propietarios (
  propietario_id INT PRIMARY KEY COMMENT 'Identificador del propietario',
  nombre VARCHAR(40) NOT NULL COMMENT 'Nombre de pila del propietario',
  apellido VARCHAR(40) NOT NULL COMMENT 'Apellido del propietario',
  rut VARCHAR(12) NOT NULL COMMENT 'RUT del propietario',
  telefono VARCHAR(20) COMMENT 'Teléfono de contacto',
  email VARCHAR(100) COMMENT 'Correo electrónico; NULL si no lo entregó',
  fecha_registro DATE NOT NULL COMMENT 'Fecha en que el propietario se registró en la agencia'
) COMMENT='Dueños de las propiedades publicadas';

CREATE TABLE agentes (
  agente_id INT PRIMARY KEY COMMENT 'Identificador del agente inmobiliario',
  nombre VARCHAR(40) NOT NULL COMMENT 'Nombre de pila del agente',
  apellido VARCHAR(40) NOT NULL COMMENT 'Apellido del agente',
  fecha_ingreso DATE NOT NULL COMMENT 'Fecha de ingreso a la agencia',
  comision_pct DECIMAL(4,2) NOT NULL COMMENT 'Porcentaje de comisión del agente (2.50 = 2,5%)',
  supervisor_id INT COMMENT 'Agente supervisor (agente_id); NULL si no tiene supervisor',
  estado VARCHAR(10) NOT NULL COMMENT 'Estado del agente: activo, inactivo',
  FOREIGN KEY (supervisor_id) REFERENCES agentes(agente_id)
) COMMENT='Agentes inmobiliarios de la agencia';

CREATE TABLE clientes (
  cliente_id INT PRIMARY KEY COMMENT 'Identificador del cliente (comprador o arrendatario)',
  nombre VARCHAR(40) NOT NULL COMMENT 'Nombre de pila del cliente',
  apellido VARCHAR(40) NOT NULL COMMENT 'Apellido del cliente',
  email VARCHAR(100) COMMENT 'Correo electrónico; NULL si no lo entregó',
  comuna_id INT COMMENT 'Comuna donde reside el cliente; NULL si es desconocida',
  fecha_registro DATE NOT NULL COMMENT 'Fecha de registro del cliente',
  FOREIGN KEY (comuna_id) REFERENCES comunas(comuna_id)
) COMMENT='Clientes interesados en comprar o arrendar';

CREATE TABLE propiedades (
  propiedad_id INT PRIMARY KEY COMMENT 'Identificador de la propiedad',
  propietario_id INT NOT NULL COMMENT 'Dueño de la propiedad',
  comuna_id INT NOT NULL COMMENT 'Comuna donde se ubica la propiedad',
  agente_id INT NOT NULL COMMENT 'Agente que captó y publica la propiedad',
  direccion VARCHAR(100) NOT NULL COMMENT 'Dirección de la propiedad',
  tipo VARCHAR(15) NOT NULL COMMENT 'Tipo de propiedad: casa, departamento, oficina, local, terreno',
  operacion VARCHAR(10) NOT NULL COMMENT 'Operación ofrecida: venta, arriendo',
  superficie_m2 DECIMAL(8,2) NOT NULL COMMENT 'Superficie útil en metros cuadrados',
  dormitorios INT COMMENT 'Cantidad de dormitorios; NULL si no aplica (oficina, local, terreno)',
  banos INT COMMENT 'Cantidad de baños; NULL si no aplica',
  precio_publicado DECIMAL(14,2) NOT NULL COMMENT 'Precio publicado en CLP: valor total si es venta, canon mensual si es arriendo',
  fecha_publicacion DATE NOT NULL COMMENT 'Fecha de publicación de la propiedad',
  estado VARCHAR(12) NOT NULL COMMENT 'Estado: disponible, reservada, vendida, arrendada, retirada',
  FOREIGN KEY (propietario_id) REFERENCES propietarios(propietario_id),
  FOREIGN KEY (comuna_id) REFERENCES comunas(comuna_id),
  FOREIGN KEY (agente_id) REFERENCES agentes(agente_id)
) COMMENT='Propiedades publicadas por la agencia';

CREATE TABLE visitas (
  visita_id INT PRIMARY KEY COMMENT 'Identificador de la visita',
  propiedad_id INT NOT NULL COMMENT 'Propiedad visitada',
  cliente_id INT NOT NULL COMMENT 'Cliente que realizó la visita',
  agente_id INT NOT NULL COMMENT 'Agente que acompañó la visita',
  fecha_hora DATETIME NOT NULL COMMENT 'Fecha y hora de la visita',
  resultado VARCHAR(15) NOT NULL COMMENT 'Resultado: interesado, no_interesado, oferta, pendiente',
  calificacion TINYINT COMMENT 'Calificación de la propiedad dada por el cliente (1 a 5); NULL si no calificó',
  FOREIGN KEY (propiedad_id) REFERENCES propiedades(propiedad_id),
  FOREIGN KEY (cliente_id) REFERENCES clientes(cliente_id),
  FOREIGN KEY (agente_id) REFERENCES agentes(agente_id)
) COMMENT='Visitas de clientes a propiedades';

CREATE TABLE contratos (
  contrato_id INT PRIMARY KEY COMMENT 'Identificador del contrato',
  propiedad_id INT NOT NULL COMMENT 'Propiedad objeto del contrato',
  cliente_id INT NOT NULL COMMENT 'Cliente comprador o arrendatario',
  agente_id INT NOT NULL COMMENT 'Agente que cerró el contrato',
  tipo VARCHAR(10) NOT NULL COMMENT 'Tipo de contrato: venta, arriendo',
  fecha_firma DATE NOT NULL COMMENT 'Fecha de firma del contrato',
  fecha_inicio DATE NOT NULL COMMENT 'Fecha de entrega o inicio del arriendo',
  fecha_termino DATE COMMENT 'Fecha de término del arriendo; NULL en ventas',
  monto DECIMAL(14,2) NOT NULL COMMENT 'Monto en CLP: precio final de venta o canon mensual de arriendo',
  comision_monto DECIMAL(12,2) NOT NULL COMMENT 'Comisión cobrada por la agencia en CLP',
  estado VARCHAR(12) NOT NULL COMMENT 'Estado: vigente, finalizado, rescindido',
  FOREIGN KEY (propiedad_id) REFERENCES propiedades(propiedad_id),
  FOREIGN KEY (cliente_id) REFERENCES clientes(cliente_id),
  FOREIGN KEY (agente_id) REFERENCES agentes(agente_id)
) COMMENT='Contratos de compraventa y arriendo';

CREATE TABLE pagos_arriendo (
  pago_id INT PRIMARY KEY COMMENT 'Identificador del pago',
  contrato_id INT NOT NULL COMMENT 'Contrato de arriendo al que corresponde',
  periodo DATE NOT NULL COMMENT 'Mes que se paga (primer día del mes)',
  fecha_vencimiento DATE NOT NULL COMMENT 'Fecha límite de pago',
  fecha_pago DATE COMMENT 'Fecha efectiva de pago; NULL si está impago',
  monto_pagado DECIMAL(12,2) COMMENT 'Monto pagado en CLP; NULL si está impago',
  metodo VARCHAR(15) COMMENT 'Método de pago: transferencia, efectivo, cheque; NULL si está impago',
  FOREIGN KEY (contrato_id) REFERENCES contratos(contrato_id)
) COMMENT='Pagos mensuales de los contratos de arriendo';

