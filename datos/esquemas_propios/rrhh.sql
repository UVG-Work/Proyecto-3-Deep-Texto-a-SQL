CREATE TABLE dept (
  dept_id INT PRIMARY KEY COMMENT 'Identificador del departamento',
  dept_nm VARCHAR(60) NOT NULL COMMENT 'Nombre del departamento',
  loc_cd CHAR(3) NOT NULL COMMENT 'Código de ciudad de la sede: SCL=Santiago, LIM=Lima, BOG=Bogotá, MEX=Ciudad de México',
  bgt_amt DECIMAL(12,2) COMMENT 'Presupuesto anual del departamento en USD',
  est_dt DATE COMMENT 'Fecha de creación del departamento'
) COMMENT='Departamentos de la empresa';

CREATE TABLE job (
  job_id INT PRIMARY KEY COMMENT 'Identificador del cargo',
  job_ttl VARCHAR(60) NOT NULL COMMENT 'Título del cargo',
  min_sal_amt DECIMAL(10,2) NOT NULL COMMENT 'Sueldo mensual mínimo de la banda salarial (USD)',
  max_sal_amt DECIMAL(10,2) NOT NULL COMMENT 'Sueldo mensual máximo de la banda salarial (USD)'
) COMMENT='Catálogo de cargos y bandas salariales';

CREATE TABLE emp (
  emp_id INT PRIMARY KEY COMMENT 'Identificador del empleado',
  fname VARCHAR(40) NOT NULL COMMENT 'Nombre de pila',
  lname VARCHAR(40) NOT NULL COMMENT 'Apellido',
  email VARCHAR(100) COMMENT 'Correo corporativo',
  gender_cd CHAR(1) COMMENT 'Género: F=femenino, M=masculino',
  birth_dt DATE COMMENT 'Fecha de nacimiento',
  hire_dt DATE NOT NULL COMMENT 'Fecha de contratación',
  term_dt DATE COMMENT 'Fecha de desvinculación; NULL si sigue activo',
  job_id INT NOT NULL COMMENT 'Cargo actual',
  dept_id INT NOT NULL COMMENT 'Departamento actual',
  mgr_id INT COMMENT 'Jefe directo (emp_id); NULL para el gerente general',
  sal_amt DECIMAL(10,2) NOT NULL COMMENT 'Sueldo mensual actual en USD',
  comm_pct DECIMAL(4,2) COMMENT 'Porcentaje de comisión sobre ventas (0.10 = 10%); NULL si no aplica',
  FOREIGN KEY (job_id) REFERENCES job(job_id),
  FOREIGN KEY (dept_id) REFERENCES dept(dept_id),
  FOREIGN KEY (mgr_id) REFERENCES emp(emp_id)
) COMMENT='Empleados de la empresa';

CREATE TABLE sal_hist (
  sal_hist_id INT PRIMARY KEY COMMENT 'Identificador del registro de historial',
  emp_id INT NOT NULL COMMENT 'Empleado',
  eff_dt DATE NOT NULL COMMENT 'Fecha desde la que rige el sueldo',
  sal_amt DECIMAL(10,2) NOT NULL COMMENT 'Sueldo mensual vigente desde eff_dt (USD)',
  chg_rsn VARCHAR(40) COMMENT 'Motivo del cambio: Aumento anual, Promoción, Ajuste de mercado, Revisión inicial',
  FOREIGN KEY (emp_id) REFERENCES emp(emp_id)
) COMMENT='Historial de cambios de sueldo 2023-2025';

CREATE TABLE proj (
  proj_id INT PRIMARY KEY COMMENT 'Identificador del proyecto',
  proj_nm VARCHAR(80) NOT NULL COMMENT 'Nombre del proyecto',
  dept_id INT NOT NULL COMMENT 'Departamento responsable',
  start_dt DATE NOT NULL COMMENT 'Fecha de inicio',
  end_dt DATE COMMENT 'Fecha de término; NULL si sigue en curso',
  bgt_amt DECIMAL(12,2) COMMENT 'Presupuesto del proyecto en USD',
  stat_cd CHAR(3) NOT NULL COMMENT 'Estado: ACT=activo, CMP=completado, HLD=en pausa',
  FOREIGN KEY (dept_id) REFERENCES dept(dept_id)
) COMMENT='Proyectos internos';

CREATE TABLE emp_proj (
  emp_id INT NOT NULL COMMENT 'Empleado asignado',
  proj_id INT NOT NULL COMMENT 'Proyecto',
  role_nm VARCHAR(40) NOT NULL COMMENT 'Rol del empleado en el proyecto',
  alloc_pct INT NOT NULL COMMENT 'Porcentaje de dedicación al proyecto (0-100)',
  asgn_dt DATE NOT NULL COMMENT 'Fecha de asignación',
  PRIMARY KEY (emp_id, proj_id),
  FOREIGN KEY (emp_id) REFERENCES emp(emp_id),
  FOREIGN KEY (proj_id) REFERENCES proj(proj_id)
) COMMENT='Asignación de empleados a proyectos';

CREATE TABLE lv_req (
  lv_id INT PRIMARY KEY COMMENT 'Identificador de la solicitud de permiso',
  emp_id INT NOT NULL COMMENT 'Empleado solicitante',
  lv_type_cd CHAR(3) NOT NULL COMMENT 'Tipo de permiso: VAC=vacaciones, ENF=licencia médica, PER=permiso personal',
  start_dt DATE NOT NULL COMMENT 'Primer día del permiso',
  end_dt DATE NOT NULL COMMENT 'Último día del permiso',
  appr_flg CHAR(1) COMMENT 'Aprobación: Y=aprobada, N=rechazada, NULL=pendiente',
  FOREIGN KEY (emp_id) REFERENCES emp(emp_id)
) COMMENT='Solicitudes de vacaciones y permisos';

CREATE TABLE perf_rev (
  rev_id INT PRIMARY KEY COMMENT 'Identificador de la evaluación',
  emp_id INT NOT NULL COMMENT 'Empleado evaluado',
  rvwr_id INT NOT NULL COMMENT 'Empleado que realiza la evaluación',
  rev_dt DATE NOT NULL COMMENT 'Fecha de la evaluación de desempeño',
  score DECIMAL(3,1) NOT NULL COMMENT 'Puntaje de desempeño de 1.0 a 5.0',
  FOREIGN KEY (emp_id) REFERENCES emp(emp_id),
  FOREIGN KEY (rvwr_id) REFERENCES emp(emp_id)
) COMMENT='Evaluaciones de desempeño anuales';

