CREATE TABLE sucursales (
  id_sucursal INT PRIMARY KEY COMMENT 'Identificador de la sucursal',
  nombre VARCHAR(60) NOT NULL COMMENT 'Nombre de la sucursal',
  ciudad VARCHAR(40) NOT NULL COMMENT 'Ciudad donde se ubica',
  region VARCHAR(40) NOT NULL COMMENT 'Región del país',
  fecha_apertura DATE NOT NULL COMMENT 'Fecha de apertura de la sucursal'
) COMMENT='Sucursales del banco';

CREATE TABLE clientes (
  id_cliente INT PRIMARY KEY COMMENT 'Identificador del cliente',
  nombre VARCHAR(40) NOT NULL COMMENT 'Nombre del cliente',
  apellido VARCHAR(40) NOT NULL COMMENT 'Apellido del cliente',
  rut VARCHAR(12) NOT NULL UNIQUE COMMENT 'RUT (documento de identidad)',
  fecha_nacimiento DATE COMMENT 'Fecha de nacimiento',
  email VARCHAR(100) COMMENT 'Correo electrónico; puede faltar',
  telefono VARCHAR(20) COMMENT 'Teléfono de contacto; puede faltar',
  segmento VARCHAR(20) NOT NULL COMMENT 'Segmento comercial: Personas, Pyme o Premium',
  fecha_registro DATE NOT NULL COMMENT 'Fecha en que se hizo cliente',
  id_sucursal INT NOT NULL COMMENT 'Sucursal de origen del cliente',
  FOREIGN KEY (id_sucursal) REFERENCES sucursales(id_sucursal)
) COMMENT='Clientes del banco';

CREATE TABLE cuentas (
  id_cuenta INT PRIMARY KEY COMMENT 'Identificador de la cuenta',
  id_cliente INT NOT NULL COMMENT 'Titular de la cuenta',
  numero_cuenta VARCHAR(20) NOT NULL UNIQUE COMMENT 'Número de cuenta',
  tipo_cuenta VARCHAR(20) NOT NULL COMMENT 'Tipo: Corriente, Ahorro o Vista',
  saldo DECIMAL(14,2) NOT NULL COMMENT 'Saldo actual en pesos',
  fecha_apertura DATE NOT NULL COMMENT 'Fecha de apertura',
  estado VARCHAR(12) NOT NULL COMMENT 'Estado: Activa, Bloqueada o Cerrada',
  fecha_cierre DATE COMMENT 'Fecha de cierre; NULL si no está cerrada',
  FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente)
) COMMENT='Cuentas bancarias';

CREATE TABLE transacciones (
  id_transaccion INT PRIMARY KEY COMMENT 'Identificador de la transacción',
  id_cuenta INT NOT NULL COMMENT 'Cuenta de origen',
  fecha_hora DATETIME NOT NULL COMMENT 'Fecha y hora de la transacción',
  tipo VARCHAR(20) NOT NULL COMMENT 'Tipo: Depósito, Retiro, Transferencia o Pago',
  monto DECIMAL(14,2) NOT NULL COMMENT 'Monto en pesos',
  canal VARCHAR(20) NOT NULL COMMENT 'Canal: Sucursal, Cajero, Web o App',
  id_cuenta_destino INT COMMENT 'Cuenta de destino, solo para transferencias internas',
  descripcion VARCHAR(100) COMMENT 'Glosa opcional',
  FOREIGN KEY (id_cuenta) REFERENCES cuentas(id_cuenta),
  FOREIGN KEY (id_cuenta_destino) REFERENCES cuentas(id_cuenta)
) COMMENT='Movimientos de las cuentas';

CREATE TABLE prestamos (
  id_prestamo INT PRIMARY KEY COMMENT 'Identificador del préstamo',
  id_cliente INT NOT NULL COMMENT 'Cliente deudor',
  id_sucursal INT NOT NULL COMMENT 'Sucursal que otorgó el préstamo',
  tipo_prestamo VARCHAR(20) NOT NULL COMMENT 'Tipo: Hipotecario, Consumo o Automotriz',
  monto_otorgado DECIMAL(14,2) NOT NULL COMMENT 'Monto prestado en pesos',
  tasa_interes DECIMAL(5,2) NOT NULL COMMENT 'Tasa de interés anual en porcentaje',
  plazo_meses INT NOT NULL COMMENT 'Plazo del préstamo en meses',
  fecha_otorgamiento DATE NOT NULL COMMENT 'Fecha en que se otorgó',
  estado VARCHAR(12) NOT NULL COMMENT 'Estado: Vigente, Pagado o Moroso',
  FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente),
  FOREIGN KEY (id_sucursal) REFERENCES sucursales(id_sucursal)
) COMMENT='Préstamos otorgados a clientes';

CREATE TABLE pagos_prestamo (
  id_pago INT PRIMARY KEY COMMENT 'Identificador del pago',
  id_prestamo INT NOT NULL COMMENT 'Préstamo al que corresponde el pago',
  fecha_pago DATE NOT NULL COMMENT 'Fecha en que se pagó la cuota',
  monto_pagado DECIMAL(14,2) NOT NULL COMMENT 'Monto pagado en pesos',
  dias_atraso INT NOT NULL DEFAULT 0 COMMENT 'Días de atraso respecto del vencimiento de la cuota',
  FOREIGN KEY (id_prestamo) REFERENCES prestamos(id_prestamo)
) COMMENT='Pagos de cuotas de préstamos';

CREATE TABLE tarjetas (
  id_tarjeta INT PRIMARY KEY COMMENT 'Identificador de la tarjeta',
  id_cliente INT NOT NULL COMMENT 'Titular de la tarjeta',
  id_cuenta INT COMMENT 'Cuenta asociada (solo tarjetas de débito)',
  tipo_tarjeta VARCHAR(10) NOT NULL COMMENT 'Tipo: Débito o Crédito',
  marca VARCHAR(20) NOT NULL COMMENT 'Marca: Visa, Mastercard o American Express',
  ultimos_digitos CHAR(4) NOT NULL COMMENT 'Últimos cuatro dígitos de la tarjeta',
  cupo_limite DECIMAL(12,2) COMMENT 'Cupo de crédito en pesos; NULL en tarjetas de débito',
  fecha_emision DATE NOT NULL COMMENT 'Fecha de emisión',
  fecha_vencimiento DATE NOT NULL COMMENT 'Fecha de vencimiento',
  activa TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1 si la tarjeta está activa, 0 si está bloqueada',
  FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente),
  FOREIGN KEY (id_cuenta) REFERENCES cuentas(id_cuenta)
) COMMENT='Tarjetas de débito y crédito';

