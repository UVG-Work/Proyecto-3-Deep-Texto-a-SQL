CREATE TABLE cine (
  id_cine INT PRIMARY KEY COMMENT 'Identificador del cine',
  nom VARCHAR(60) NOT NULL COMMENT 'Nombre del complejo de cine',
  ciudad VARCHAR(40) NOT NULL COMMENT 'Ciudad donde se ubica',
  dir VARCHAR(100) NOT NULL COMMENT 'Dirección del complejo',
  tel VARCHAR(20) COMMENT 'Teléfono de contacto; NULL si no tiene',
  f_aper DATE NOT NULL COMMENT 'Fecha de apertura del cine'
) COMMENT='Complejos de la cadena de cines';

CREATE TABLE sala (
  id_sala INT PRIMARY KEY COMMENT 'Identificador de la sala',
  id_cine INT NOT NULL COMMENT 'Cine al que pertenece la sala',
  num_sala TINYINT NOT NULL COMMENT 'Número de la sala dentro del cine',
  tipo VARCHAR(4) NOT NULL COMMENT 'Tipo de sala: 2D, 3D, IMAX, VIP',
  cap SMALLINT NOT NULL COMMENT 'Capacidad de butacas',
  FOREIGN KEY (id_cine) REFERENCES cine(id_cine)
) COMMENT='Salas de proyección de cada cine';

CREATE TABLE pel (
  id_pel INT PRIMARY KEY COMMENT 'Identificador de la película',
  tit VARCHAR(80) NOT NULL COMMENT 'Título de la película',
  gen VARCHAR(20) NOT NULL COMMENT 'Género: Acción, Comedia, Drama, Terror, Animación, Ciencia ficción, Documental',
  dur_min SMALLINT NOT NULL COMMENT 'Duración en minutos',
  clasif VARCHAR(3) NOT NULL COMMENT 'Clasificación: TE=todo espectador, 7=mayores de 7, 14=mayores de 14, 18=mayores de 18',
  f_estr DATE NOT NULL COMMENT 'Fecha de estreno en la cadena',
  pais CHAR(2) COMMENT 'País de origen (código ISO): US, CL, MX, AR, ES, FR, JP, KR',
  id_pel_ant INT COMMENT 'Película anterior de la misma saga (id_pel); NULL si no es secuela',
  FOREIGN KEY (id_pel_ant) REFERENCES pel(id_pel)
) COMMENT='Catálogo de películas';

CREATE TABLE func (
  id_func INT PRIMARY KEY COMMENT 'Identificador de la función',
  id_pel INT NOT NULL COMMENT 'Película proyectada',
  id_sala INT NOT NULL COMMENT 'Sala donde se proyecta',
  f_func DATE NOT NULL COMMENT 'Fecha de la función',
  hr_ini TIME NOT NULL COMMENT 'Hora de inicio de la función',
  prec DECIMAL(8,2) NOT NULL COMMENT 'Precio base de la entrada en pesos chilenos',
  idioma CHAR(3) NOT NULL COMMENT 'Idioma: DOB=doblada al español, SUB=subtitulada',
  est CHAR(3) NOT NULL COMMENT 'Estado: PRG=programada, REA=realizada, CAN=cancelada',
  FOREIGN KEY (id_pel) REFERENCES pel(id_pel),
  FOREIGN KEY (id_sala) REFERENCES sala(id_sala)
) COMMENT='Funciones (proyecciones) programadas';

CREATE TABLE cli (
  id_cli INT PRIMARY KEY COMMENT 'Identificador del cliente',
  nom VARCHAR(40) NOT NULL COMMENT 'Nombre del cliente',
  ape VARCHAR(40) NOT NULL COMMENT 'Apellido del cliente',
  email VARCHAR(100) COMMENT 'Correo electrónico; NULL si no lo entregó',
  f_nac DATE COMMENT 'Fecha de nacimiento',
  f_reg DATE NOT NULL COMMENT 'Fecha de registro en el programa de socios',
  nivel CHAR(3) NOT NULL COMMENT 'Nivel de socio: BRO=bronce, PLA=plata, ORO=oro',
  id_cli_ref INT COMMENT 'Cliente que lo refirió al programa (id_cli); NULL si llegó solo',
  FOREIGN KEY (id_cli_ref) REFERENCES cli(id_cli)
) COMMENT='Clientes registrados en el programa de socios';

CREATE TABLE bol (
  id_bol INT PRIMARY KEY COMMENT 'Identificador del boleto',
  id_func INT NOT NULL COMMENT 'Función para la que se emitió',
  id_cli INT COMMENT 'Cliente socio que compró; NULL si fue venta sin registro',
  f_compra DATETIME NOT NULL COMMENT 'Fecha y hora de compra',
  asiento VARCHAR(4) NOT NULL COMMENT 'Butaca asignada (fila y número, ej. F12)',
  prec_pag DECIMAL(8,2) NOT NULL COMMENT 'Precio efectivamente pagado en pesos (puede incluir descuento)',
  canal CHAR(3) NOT NULL COMMENT 'Canal de venta: TAQ=taquilla, WEB=sitio web, APP=aplicación móvil',
  est CHAR(3) NOT NULL COMMENT 'Estado del boleto: VAL=vigente, USA=usado, REE=reembolsado',
  FOREIGN KEY (id_func) REFERENCES func(id_func),
  FOREIGN KEY (id_cli) REFERENCES cli(id_cli)
) COMMENT='Boletos (entradas) vendidos';

CREATE TABLE prod_conf (
  id_prod INT PRIMARY KEY COMMENT 'Identificador del producto',
  nom VARCHAR(60) NOT NULL COMMENT 'Nombre del producto',
  cat CHAR(3) NOT NULL COMMENT 'Categoría: CAB=cabritas (palomitas), BEB=bebida, DUL=dulces, COM=combo',
  prec DECIMAL(8,2) NOT NULL COMMENT 'Precio de lista en pesos',
  activo TINYINT(1) NOT NULL COMMENT 'Disponible a la venta: 1=sí, 0=descontinuado'
) COMMENT='Productos de confitería';

CREATE TABLE vta_conf (
  id_vta INT PRIMARY KEY COMMENT 'Identificador de la línea de venta de confitería',
  id_cine INT NOT NULL COMMENT 'Cine donde se hizo la venta',
  id_cli INT COMMENT 'Cliente socio; NULL si fue venta sin registro',
  id_prod INT NOT NULL COMMENT 'Producto vendido',
  f_vta DATETIME NOT NULL COMMENT 'Fecha y hora de la venta',
  cant SMALLINT NOT NULL COMMENT 'Unidades vendidas',
  prec_unit DECIMAL(8,2) NOT NULL COMMENT 'Precio unitario cobrado en pesos',
  med_pago CHAR(3) NOT NULL COMMENT 'Medio de pago: EFE=efectivo, TAR=tarjeta, APP=billetera de la app',
  FOREIGN KEY (id_cine) REFERENCES cine(id_cine),
  FOREIGN KEY (id_cli) REFERENCES cli(id_cli),
  FOREIGN KEY (id_prod) REFERENCES prod_conf(id_prod)
) COMMENT='Ventas de confitería (una fila por producto vendido)';

