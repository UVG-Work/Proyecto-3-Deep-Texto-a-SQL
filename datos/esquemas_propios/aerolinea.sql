CREATE TABLE airports (
  airport_id INT PRIMARY KEY COMMENT 'Identificador del aeropuerto',
  iata_code CHAR(3) NOT NULL UNIQUE COMMENT 'Código IATA de tres letras',
  name VARCHAR(100) NOT NULL COMMENT 'Nombre del aeropuerto',
  city VARCHAR(60) NOT NULL COMMENT 'Ciudad del aeropuerto',
  country VARCHAR(60) NOT NULL COMMENT 'País del aeropuerto'
) COMMENT='Aeropuertos donde opera la aerolínea';

CREATE TABLE aircraft (
  aircraft_id INT PRIMARY KEY COMMENT 'Identificador del avión',
  registration VARCHAR(10) NOT NULL UNIQUE COMMENT 'Matrícula del avión',
  model VARCHAR(40) NOT NULL COMMENT 'Modelo del avión',
  manufacturer VARCHAR(40) NOT NULL COMMENT 'Fabricante del avión',
  seat_capacity SMALLINT NOT NULL COMMENT 'Cantidad total de asientos',
  year_built SMALLINT NOT NULL COMMENT 'Año de fabricación',
  last_maintenance DATE COMMENT 'Fecha de la última mantención; NULL si aún no tiene'
) COMMENT='Flota de aviones';

CREATE TABLE flights (
  flight_id INT PRIMARY KEY COMMENT 'Identificador del vuelo',
  flight_number VARCHAR(8) NOT NULL COMMENT 'Número comercial del vuelo, ej. SK102',
  origin_airport_id INT NOT NULL COMMENT 'Aeropuerto de origen',
  destination_airport_id INT NOT NULL COMMENT 'Aeropuerto de destino',
  aircraft_id INT NOT NULL COMMENT 'Avión asignado al vuelo',
  departure_time DATETIME NOT NULL COMMENT 'Fecha y hora programada de salida',
  arrival_time DATETIME NOT NULL COMMENT 'Fecha y hora programada de llegada',
  status VARCHAR(12) NOT NULL COMMENT 'Estado: scheduled, arrived, delayed o cancelled',
  base_price DECIMAL(8,2) NOT NULL COMMENT 'Tarifa base en clase económica, en dólares',
  FOREIGN KEY (origin_airport_id) REFERENCES airports(airport_id),
  FOREIGN KEY (destination_airport_id) REFERENCES airports(airport_id),
  FOREIGN KEY (aircraft_id) REFERENCES aircraft(aircraft_id)
) COMMENT='Vuelos programados';

CREATE TABLE passengers (
  passenger_id INT PRIMARY KEY COMMENT 'Identificador del pasajero',
  first_name VARCHAR(50) NOT NULL COMMENT 'Nombre del pasajero',
  last_name VARCHAR(50) NOT NULL COMMENT 'Apellido del pasajero',
  birth_date DATE NOT NULL COMMENT 'Fecha de nacimiento',
  nationality VARCHAR(40) NOT NULL COMMENT 'Nacionalidad',
  email VARCHAR(100) COMMENT 'Correo electrónico',
  frequent_flyer_number VARCHAR(12) COMMENT 'Número de viajero frecuente; NULL si no es socio'
) COMMENT='Pasajeros registrados';

CREATE TABLE bookings (
  booking_id INT PRIMARY KEY COMMENT 'Identificador de la reserva',
  passenger_id INT NOT NULL COMMENT 'Pasajero que reserva',
  flight_id INT NOT NULL COMMENT 'Vuelo reservado',
  booking_date DATETIME NOT NULL COMMENT 'Fecha y hora en que se hizo la reserva',
  seat_number VARCHAR(4) COMMENT 'Asiento asignado; NULL si aún no elige',
  travel_class VARCHAR(10) NOT NULL COMMENT 'Clase: economy, business o first',
  price_paid DECIMAL(8,2) NOT NULL COMMENT 'Precio pagado en dólares',
  checked_in TINYINT(1) NOT NULL DEFAULT 0 COMMENT '1 si el pasajero hizo check-in',
  FOREIGN KEY (passenger_id) REFERENCES passengers(passenger_id),
  FOREIGN KEY (flight_id) REFERENCES flights(flight_id)
) COMMENT='Reservas de pasajes';

CREATE TABLE crew_members (
  crew_id INT PRIMARY KEY COMMENT 'Identificador del tripulante',
  first_name VARCHAR(50) NOT NULL COMMENT 'Nombre del tripulante',
  last_name VARCHAR(50) NOT NULL COMMENT 'Apellido del tripulante',
  role VARCHAR(20) NOT NULL COMMENT 'Cargo: pilot, copilot o flight attendant',
  hire_date DATE NOT NULL COMMENT 'Fecha de contratación',
  base_airport_id INT NOT NULL COMMENT 'Aeropuerto base del tripulante',
  FOREIGN KEY (base_airport_id) REFERENCES airports(airport_id)
) COMMENT='Tripulación (pilotos y auxiliares de vuelo)';

CREATE TABLE flight_crew (
  flight_id INT NOT NULL COMMENT 'Vuelo',
  crew_id INT NOT NULL COMMENT 'Tripulante asignado al vuelo',
  PRIMARY KEY (flight_id, crew_id),
  FOREIGN KEY (flight_id) REFERENCES flights(flight_id),
  FOREIGN KEY (crew_id) REFERENCES crew_members(crew_id)
) COMMENT='Asignación de tripulantes a vuelos';

