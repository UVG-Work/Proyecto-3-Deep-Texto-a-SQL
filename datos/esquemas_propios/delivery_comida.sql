CREATE TABLE restaurantes (
  id_restaurante INT PRIMARY KEY COMMENT 'Identificador del restaurante',
  nombre VARCHAR(80) NOT NULL COMMENT 'Nombre comercial del restaurante',
  tipo_cocina VARCHAR(30) NOT NULL COMMENT 'Tipo de cocina: italiana, japonesa, mexicana, etc.',
  ciudad VARCHAR(50) NOT NULL COMMENT 'Ciudad donde se ubica',
  direccion VARCHAR(120) NOT NULL COMMENT 'Dirección del local',
  costo_envio DECIMAL(6,2) NOT NULL COMMENT 'Costo de envío que cobra el restaurante',
  fecha_alta DATE NOT NULL COMMENT 'Fecha en que se unió a la plataforma'
) COMMENT='Restaurantes asociados a la plataforma de delivery';

CREATE TABLE platos (
  id_plato INT PRIMARY KEY COMMENT 'Identificador del plato',
  id_restaurante INT NOT NULL COMMENT 'Restaurante que ofrece el plato',
  nombre VARCHAR(80) NOT NULL COMMENT 'Nombre del plato',
  categoria VARCHAR(30) NOT NULL COMMENT 'Categoría: entrada, principal, postre o bebida',
  precio DECIMAL(8,2) NOT NULL COMMENT 'Precio actual del plato',
  es_vegetariano TINYINT(1) NOT NULL DEFAULT 0 COMMENT '1 si el plato es vegetariano',
  disponible TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1 si está disponible para pedir',
  FOREIGN KEY (id_restaurante) REFERENCES restaurantes(id_restaurante)
) COMMENT='Menú de platos de cada restaurante';

CREATE TABLE clientes (
  id_cliente INT PRIMARY KEY COMMENT 'Identificador del cliente',
  nombre VARCHAR(50) NOT NULL COMMENT 'Nombre del cliente',
  apellido VARCHAR(50) NOT NULL COMMENT 'Apellido del cliente',
  email VARCHAR(100) NOT NULL COMMENT 'Correo electrónico',
  telefono VARCHAR(20) COMMENT 'Teléfono de contacto (opcional)',
  ciudad VARCHAR(50) NOT NULL COMMENT 'Ciudad del cliente',
  fecha_registro DATE NOT NULL COMMENT 'Fecha de registro en la aplicación'
) COMMENT='Clientes de la aplicación';

CREATE TABLE repartidores (
  id_repartidor INT PRIMARY KEY COMMENT 'Identificador del repartidor',
  nombre VARCHAR(80) NOT NULL COMMENT 'Nombre completo del repartidor',
  vehiculo VARCHAR(15) NOT NULL COMMENT 'Vehículo: bicicleta, moto o auto',
  ciudad VARCHAR(50) NOT NULL COMMENT 'Ciudad donde reparte',
  fecha_ingreso DATE NOT NULL COMMENT 'Fecha de ingreso a la plataforma',
  activo TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1 si el repartidor sigue activo'
) COMMENT='Repartidores de la plataforma';

CREATE TABLE pedidos (
  id_pedido INT PRIMARY KEY COMMENT 'Identificador del pedido',
  id_cliente INT NOT NULL COMMENT 'Cliente que hace el pedido',
  id_restaurante INT NOT NULL COMMENT 'Restaurante al que se pide',
  id_repartidor INT COMMENT 'Repartidor asignado; NULL si el pedido se canceló antes de asignar',
  fecha_pedido DATETIME NOT NULL COMMENT 'Fecha y hora en que se realizó el pedido',
  fecha_entrega DATETIME COMMENT 'Fecha y hora de entrega; NULL si no se entregó',
  estado VARCHAR(15) NOT NULL COMMENT 'Estado: entregado, cancelado o en camino',
  metodo_pago VARCHAR(20) NOT NULL COMMENT 'Medio de pago: tarjeta, efectivo o billetera digital',
  propina DECIMAL(6,2) NOT NULL DEFAULT 0 COMMENT 'Propina para el repartidor',
  FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente),
  FOREIGN KEY (id_restaurante) REFERENCES restaurantes(id_restaurante),
  FOREIGN KEY (id_repartidor) REFERENCES repartidores(id_repartidor)
) COMMENT='Pedidos realizados por los clientes';

CREATE TABLE detalle_pedido (
  id_pedido INT NOT NULL COMMENT 'Pedido',
  id_plato INT NOT NULL COMMENT 'Plato incluido en el pedido',
  cantidad SMALLINT NOT NULL COMMENT 'Unidades pedidas del plato',
  precio_unitario DECIMAL(8,2) NOT NULL COMMENT 'Precio del plato al momento del pedido',
  PRIMARY KEY (id_pedido, id_plato),
  FOREIGN KEY (id_pedido) REFERENCES pedidos(id_pedido),
  FOREIGN KEY (id_plato) REFERENCES platos(id_plato)
) COMMENT='Líneas de cada pedido (platos y cantidades)';

CREATE TABLE resenas (
  id_resena INT PRIMARY KEY COMMENT 'Identificador de la reseña',
  id_pedido INT NOT NULL UNIQUE COMMENT 'Pedido evaluado',
  puntuacion TINYINT NOT NULL COMMENT 'Puntuación de 1 a 5 estrellas',
  comentario VARCHAR(255) COMMENT 'Comentario del cliente (opcional)',
  fecha_resena DATE NOT NULL COMMENT 'Fecha en que se escribió la reseña',
  FOREIGN KEY (id_pedido) REFERENCES pedidos(id_pedido)
) COMMENT='Reseñas de los clientes sobre sus pedidos';

