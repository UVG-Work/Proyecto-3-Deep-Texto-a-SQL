CREATE TABLE dueno (
  id_dueno INT PRIMARY KEY COMMENT 'Identificador del dueño',
  nom VARCHAR(40) NOT NULL COMMENT 'Nombre del dueño',
  ape VARCHAR(40) NOT NULL COMMENT 'Apellido del dueño',
  tel VARCHAR(20) COMMENT 'Teléfono de contacto; NULL si no lo entregó',
  email VARCHAR(100) COMMENT 'Correo electrónico; NULL si no lo entregó',
  ciudad VARCHAR(40) NOT NULL COMMENT 'Ciudad de residencia del dueño',
  f_reg DATE NOT NULL COMMENT 'Fecha de registro del dueño en la clínica'
) COMMENT='Dueños (clientes) de la clínica veterinaria';

CREATE TABLE masc (
  id_masc INT PRIMARY KEY COMMENT 'Identificador de la mascota',
  id_dueno INT NOT NULL COMMENT 'Dueño de la mascota',
  nom VARCHAR(40) NOT NULL COMMENT 'Nombre de la mascota',
  esp VARCHAR(10) NOT NULL COMMENT 'Especie: perro, gato, ave, conejo, reptil',
  raza VARCHAR(40) COMMENT 'Raza; NULL si es mestizo o se desconoce',
  sexo CHAR(1) NOT NULL COMMENT 'Sexo: M=macho, H=hembra',
  f_nac DATE COMMENT 'Fecha de nacimiento; NULL si se desconoce',
  peso_kg DECIMAL(5,2) COMMENT 'Peso actual en kilogramos',
  esteril TINYINT(1) NOT NULL COMMENT 'Esterilizada: 1=sí, 0=no',
  chip VARCHAR(15) COMMENT 'Número de microchip; NULL si no tiene',
  FOREIGN KEY (id_dueno) REFERENCES dueno(id_dueno)
) COMMENT='Mascotas registradas';

CREATE TABLE vet (
  id_vet INT PRIMARY KEY COMMENT 'Identificador del veterinario',
  nom VARCHAR(40) NOT NULL COMMENT 'Nombre del veterinario',
  ape VARCHAR(40) NOT NULL COMMENT 'Apellido del veterinario',
  espec VARCHAR(20) NOT NULL COMMENT 'Especialidad: general, cirugia, dermatologia, exoticos',
  f_ingr DATE NOT NULL COMMENT 'Fecha de ingreso a la clínica',
  f_salida DATE COMMENT 'Fecha en que dejó la clínica; NULL si sigue trabajando'
) COMMENT='Veterinarios de la clínica';

CREATE TABLE cons (
  id_cons INT PRIMARY KEY COMMENT 'Identificador de la consulta',
  id_masc INT NOT NULL COMMENT 'Mascota atendida',
  id_vet INT NOT NULL COMMENT 'Veterinario que atiende',
  f_cons DATETIME NOT NULL COMMENT 'Fecha y hora de la consulta',
  tipo VARCHAR(12) NOT NULL COMMENT 'Tipo de consulta: control, urgencia, cirugia, vacunacion',
  motivo VARCHAR(80) COMMENT 'Motivo de la consulta',
  estado VARCHAR(12) NOT NULL COMMENT 'Estado: atendida, cancelada, no_asistio',
  peso_kg DECIMAL(5,2) COMMENT 'Peso de la mascota registrado en la consulta; NULL si no fue atendida',
  monto DECIMAL(10,2) COMMENT 'Honorario de la consulta en pesos chilenos (sin tratamientos); NULL si no fue atendida',
  FOREIGN KEY (id_masc) REFERENCES masc(id_masc),
  FOREIGN KEY (id_vet) REFERENCES vet(id_vet)
) COMMENT='Consultas veterinarias agendadas';

CREATE TABLE trat (
  id_trat INT PRIMARY KEY COMMENT 'Identificador del tratamiento',
  id_cons INT NOT NULL COMMENT 'Consulta en la que se indicó',
  medic VARCHAR(40) NOT NULL COMMENT 'Medicamento o procedimiento indicado',
  dosis VARCHAR(30) COMMENT 'Dosis indicada',
  dias INT COMMENT 'Duración del tratamiento en días; NULL si es dosis única',
  costo DECIMAL(10,2) NOT NULL COMMENT 'Costo del tratamiento en pesos chilenos',
  FOREIGN KEY (id_cons) REFERENCES cons(id_cons)
) COMMENT='Tratamientos indicados en cada consulta (detalle de la consulta)';

CREATE TABLE vac (
  id_vac INT PRIMARY KEY COMMENT 'Identificador de la vacunación',
  id_masc INT NOT NULL COMMENT 'Mascota vacunada',
  id_vet INT NOT NULL COMMENT 'Veterinario que aplicó la vacuna',
  tipo_vac VARCHAR(30) NOT NULL COMMENT 'Vacuna: rabia, octuple, kc, triple felina, leucemia felina, mixomatosis',
  f_apl DATE NOT NULL COMMENT 'Fecha de aplicación',
  f_prox DATE COMMENT 'Fecha del próximo refuerzo; NULL si no requiere refuerzo',
  costo DECIMAL(10,2) NOT NULL COMMENT 'Precio cobrado por la vacuna en pesos chilenos',
  FOREIGN KEY (id_masc) REFERENCES masc(id_masc),
  FOREIGN KEY (id_vet) REFERENCES vet(id_vet)
) COMMENT='Vacunas aplicadas a las mascotas';

CREATE TABLE fact (
  id_fact INT PRIMARY KEY COMMENT 'Identificador de la factura',
  id_cons INT NOT NULL UNIQUE COMMENT 'Consulta facturada',
  f_emi DATE NOT NULL COMMENT 'Fecha de emisión',
  total DECIMAL(10,2) NOT NULL COMMENT 'Total facturado en pesos chilenos (honorario más tratamientos)',
  estado VARCHAR(10) NOT NULL COMMENT 'Estado: pagada, pendiente, anulada',
  medio VARCHAR(15) COMMENT 'Medio de pago: efectivo, tarjeta, transferencia; NULL si no está pagada',
  FOREIGN KEY (id_cons) REFERENCES cons(id_cons)
) COMMENT='Facturas emitidas por las consultas atendidas';

