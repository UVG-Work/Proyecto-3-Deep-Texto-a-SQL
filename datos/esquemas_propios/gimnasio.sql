CREATE TABLE plan (
  plan_id INT PRIMARY KEY COMMENT 'Identificador del plan',
  plan_name VARCHAR(40) NOT NULL COMMENT 'Nombre comercial del plan',
  access_lvl VARCHAR(10) NOT NULL COMMENT 'Nivel de acceso: basic=solo sala de máquinas, full=máquinas y clases, premium=todo incluido piscina',
  duration_mo INT NOT NULL COMMENT 'Duración del plan en meses',
  price DECIMAL(8,2) NOT NULL COMMENT 'Precio total del plan en USD',
  is_active TINYINT(1) NOT NULL COMMENT 'Plan vigente para la venta: 1=sí, 0=descontinuado'
) COMMENT='Catálogo de planes de membresía';

CREATE TABLE mbr (
  mbr_id INT PRIMARY KEY COMMENT 'Identificador del socio',
  first_name VARCHAR(40) NOT NULL COMMENT 'Nombre del socio',
  last_name VARCHAR(40) NOT NULL COMMENT 'Apellido del socio',
  gender CHAR(1) COMMENT 'Género: F=femenino, M=masculino; NULL si no lo informó',
  birth_date DATE COMMENT 'Fecha de nacimiento; NULL si no la informó',
  city VARCHAR(40) NOT NULL COMMENT 'Ciudad de residencia del socio',
  email VARCHAR(100) COMMENT 'Correo electrónico; NULL si no lo entregó',
  join_date DATE NOT NULL COMMENT 'Fecha de registro en el gimnasio',
  referred_by INT COMMENT 'Socio que lo refirió (mbr_id); NULL si llegó sin referido',
  FOREIGN KEY (referred_by) REFERENCES mbr(mbr_id)
) COMMENT='Socios registrados del gimnasio';

CREATE TABLE mbrship (
  mbrship_id INT PRIMARY KEY COMMENT 'Identificador de la membresía',
  mbr_id INT NOT NULL COMMENT 'Socio titular',
  plan_id INT NOT NULL COMMENT 'Plan contratado',
  start_date DATE NOT NULL COMMENT 'Fecha de inicio',
  end_date DATE NOT NULL COMMENT 'Fecha de término',
  disc_pct DECIMAL(4,2) COMMENT 'Descuento aplicado (0.10 = 10%); NULL si no tuvo descuento',
  status VARCHAR(10) NOT NULL COMMENT 'Estado: active=vigente, expired=vencida, cancelled=cancelada',
  FOREIGN KEY (mbr_id) REFERENCES mbr(mbr_id),
  FOREIGN KEY (plan_id) REFERENCES plan(plan_id)
) COMMENT='Membresías contratadas por los socios (una fila por contrato o renovación)';

CREATE TABLE pmt (
  pmt_id INT PRIMARY KEY COMMENT 'Identificador del pago',
  mbrship_id INT NOT NULL COMMENT 'Membresía a la que corresponde el pago',
  pmt_date DATE NOT NULL COMMENT 'Fecha del pago',
  amount DECIMAL(8,2) NOT NULL COMMENT 'Monto en USD',
  method VARCHAR(10) NOT NULL COMMENT 'Medio de pago: card, cash, transfer',
  status VARCHAR(10) NOT NULL COMMENT 'Estado: paid=pagado, failed=rechazado, refunded=reembolsado',
  FOREIGN KEY (mbrship_id) REFERENCES mbrship(mbrship_id)
) COMMENT='Pagos de membresías';

CREATE TABLE trainer (
  trainer_id INT PRIMARY KEY COMMENT 'Identificador del entrenador',
  first_name VARCHAR(40) NOT NULL COMMENT 'Nombre del entrenador',
  last_name VARCHAR(40) NOT NULL COMMENT 'Apellido del entrenador',
  specialty VARCHAR(15) NOT NULL COMMENT 'Especialidad: yoga, crossfit, spinning, pilates, strength',
  hire_date DATE NOT NULL COMMENT 'Fecha de contratación',
  hourly_rate DECIMAL(6,2) NOT NULL COMMENT 'Tarifa por hora de clase en USD'
) COMMENT='Entrenadores del gimnasio';

CREATE TABLE cls (
  cls_id INT PRIMARY KEY COMMENT 'Identificador de la clase',
  cls_name VARCHAR(40) NOT NULL COMMENT 'Nombre de la clase',
  trainer_id INT NOT NULL COMMENT 'Entrenador a cargo',
  room VARCHAR(10) NOT NULL COMMENT 'Sala: A, B, C, POOL',
  start_dt DATETIME NOT NULL COMMENT 'Fecha y hora de inicio',
  duration_min INT NOT NULL COMMENT 'Duración en minutos',
  capacity INT NOT NULL COMMENT 'Cupo máximo de inscritos',
  status VARCHAR(10) NOT NULL COMMENT 'Estado: scheduled=programada, completed=realizada, cancelled=cancelada',
  FOREIGN KEY (trainer_id) REFERENCES trainer(trainer_id)
) COMMENT='Clases grupales programadas';

CREATE TABLE cls_enroll (
  enroll_id INT PRIMARY KEY COMMENT 'Identificador de la inscripción',
  cls_id INT NOT NULL COMMENT 'Clase',
  mbr_id INT NOT NULL COMMENT 'Socio inscrito',
  enroll_dt DATETIME NOT NULL COMMENT 'Fecha y hora de la inscripción',
  att_status VARCHAR(10) NOT NULL COMMENT 'Asistencia: registered=inscrito (clase futura), attended=asistió, no_show=no se presentó, cancelled=anuló la inscripción',
  rating TINYINT COMMENT 'Calificación de la clase de 1 a 5 dada por el socio; NULL si no calificó',
  UNIQUE (cls_id, mbr_id),
  FOREIGN KEY (cls_id) REFERENCES cls(cls_id),
  FOREIGN KEY (mbr_id) REFERENCES mbr(mbr_id)
) COMMENT='Inscripciones de socios en clases grupales';

CREATE TABLE checkin (
  checkin_id INT PRIMARY KEY COMMENT 'Identificador del ingreso',
  mbr_id INT NOT NULL COMMENT 'Socio que ingresó',
  checkin_dt DATETIME NOT NULL COMMENT 'Fecha y hora de entrada al gimnasio',
  checkout_dt DATETIME COMMENT 'Fecha y hora de salida; NULL si no registró la salida',
  FOREIGN KEY (mbr_id) REFERENCES mbr(mbr_id)
) COMMENT='Registro de entradas y salidas en recepción';

