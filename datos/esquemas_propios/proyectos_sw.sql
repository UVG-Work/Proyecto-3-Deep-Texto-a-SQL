CREATE TABLE users (
  user_id INT PRIMARY KEY COMMENT 'Identificador del usuario',
  full_name VARCHAR(80) NOT NULL COMMENT 'Nombre completo',
  email VARCHAR(100) NOT NULL COMMENT 'Correo corporativo',
  role VARCHAR(10) NOT NULL COMMENT 'Rol: developer, qa, designer, pm, devops',
  hired_date DATE NOT NULL COMMENT 'Fecha de ingreso a la empresa',
  manager_id INT COMMENT 'Jefe directo (user_id); NULL si no reporta a nadie',
  hourly_rate DECIMAL(6,2) COMMENT 'Costo por hora en USD; NULL si no está definido',
  is_active TINYINT(1) NOT NULL COMMENT 'Usuario activo: 1=sí, 0=desactivado',
  FOREIGN KEY (manager_id) REFERENCES users(user_id)
) COMMENT='Usuarios del sistema de gestión de proyectos';

CREATE TABLE projects (
  project_id INT PRIMARY KEY COMMENT 'Identificador del proyecto',
  name VARCHAR(80) NOT NULL COMMENT 'Nombre del proyecto',
  project_key VARCHAR(10) NOT NULL COMMENT 'Clave corta del proyecto (prefijo de los issues)',
  owner_id INT NOT NULL COMMENT 'Responsable del proyecto (user_id)',
  start_date DATE NOT NULL COMMENT 'Fecha de inicio',
  end_date DATE COMMENT 'Fecha de cierre; NULL si sigue abierto',
  budget DECIMAL(12,2) COMMENT 'Presupuesto en USD; NULL si no se asignó',
  status VARCHAR(10) NOT NULL COMMENT 'Estado: planning, active, on_hold, completed, cancelled',
  FOREIGN KEY (owner_id) REFERENCES users(user_id)
) COMMENT='Proyectos de software';

CREATE TABLE sprints (
  sprint_id INT PRIMARY KEY COMMENT 'Identificador del sprint',
  project_id INT NOT NULL COMMENT 'Proyecto al que pertenece',
  name VARCHAR(40) NOT NULL COMMENT 'Nombre del sprint',
  start_date DATE NOT NULL COMMENT 'Fecha de inicio del sprint',
  end_date DATE NOT NULL COMMENT 'Fecha de término planificada',
  goal VARCHAR(150) COMMENT 'Objetivo del sprint; NULL si no se definió',
  status VARCHAR(10) NOT NULL COMMENT 'Estado: planned, active, closed',
  FOREIGN KEY (project_id) REFERENCES projects(project_id)
) COMMENT='Sprints (iteraciones) de cada proyecto';

CREATE TABLE issues (
  issue_id INT PRIMARY KEY COMMENT 'Identificador del issue',
  project_id INT NOT NULL COMMENT 'Proyecto al que pertenece',
  sprint_id INT COMMENT 'Sprint asignado; NULL si está en el backlog',
  parent_issue_id INT COMMENT 'Issue padre (issue_id) cuando es una subtarea; NULL si no tiene padre',
  title VARCHAR(150) NOT NULL COMMENT 'Título del issue',
  issue_type VARCHAR(10) NOT NULL COMMENT 'Tipo: bug, story, task, epic',
  priority VARCHAR(10) NOT NULL COMMENT 'Prioridad: lowest, low, medium, high, critical',
  status VARCHAR(12) NOT NULL COMMENT 'Estado: open, in_progress, in_review, done, closed',
  story_points TINYINT COMMENT 'Puntos de historia estimados; NULL si no se estimó',
  reporter_id INT NOT NULL COMMENT 'Usuario que reportó o creó el issue',
  assignee_id INT COMMENT 'Usuario asignado; NULL si no tiene responsable',
  created_at DATETIME NOT NULL COMMENT 'Fecha y hora de creación',
  resolved_at DATETIME COMMENT 'Fecha y hora de resolución; NULL si no está resuelto',
  due_date DATE COMMENT 'Fecha límite; NULL si no tiene',
  FOREIGN KEY (project_id) REFERENCES projects(project_id),
  FOREIGN KEY (sprint_id) REFERENCES sprints(sprint_id),
  FOREIGN KEY (parent_issue_id) REFERENCES issues(issue_id),
  FOREIGN KEY (reporter_id) REFERENCES users(user_id),
  FOREIGN KEY (assignee_id) REFERENCES users(user_id)
) COMMENT='Issues (tareas, bugs, historias) de los proyectos';

CREATE TABLE comments (
  comment_id INT PRIMARY KEY COMMENT 'Identificador del comentario',
  issue_id INT NOT NULL COMMENT 'Issue comentado',
  author_id INT NOT NULL COMMENT 'Autor del comentario (user_id)',
  body VARCHAR(300) NOT NULL COMMENT 'Texto del comentario',
  created_at DATETIME NOT NULL COMMENT 'Fecha y hora del comentario',
  FOREIGN KEY (issue_id) REFERENCES issues(issue_id),
  FOREIGN KEY (author_id) REFERENCES users(user_id)
) COMMENT='Comentarios en los issues';

CREATE TABLE time_logs (
  log_id INT PRIMARY KEY COMMENT 'Identificador del registro de horas',
  issue_id INT NOT NULL COMMENT 'Issue en el que se trabajó',
  user_id INT NOT NULL COMMENT 'Usuario que registró las horas',
  log_date DATE NOT NULL COMMENT 'Día trabajado',
  hours_spent DECIMAL(4,2) NOT NULL COMMENT 'Horas dedicadas',
  description VARCHAR(150) COMMENT 'Descripción del trabajo; NULL si no se detalló',
  FOREIGN KEY (issue_id) REFERENCES issues(issue_id),
  FOREIGN KEY (user_id) REFERENCES users(user_id)
) COMMENT='Registro de horas trabajadas por issue';

CREATE TABLE labels (
  label_id INT PRIMARY KEY COMMENT 'Identificador de la etiqueta',
  name VARCHAR(30) NOT NULL COMMENT 'Nombre de la etiqueta',
  color CHAR(7) NOT NULL COMMENT 'Color en formato hexadecimal'
) COMMENT='Etiquetas para clasificar issues';

CREATE TABLE issue_labels (
  issue_id INT NOT NULL COMMENT 'Issue etiquetado',
  label_id INT NOT NULL COMMENT 'Etiqueta aplicada',
  PRIMARY KEY (issue_id, label_id),
  FOREIGN KEY (issue_id) REFERENCES issues(issue_id),
  FOREIGN KEY (label_id) REFERENCES labels(label_id)
) COMMENT='Relación muchos a muchos entre issues y etiquetas';

