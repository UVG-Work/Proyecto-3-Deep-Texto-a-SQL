CREATE TABLE depto (
  id_depto INT PRIMARY KEY COMMENT 'Identificador del departamento académico',
  nom_depto VARCHAR(80) NOT NULL COMMENT 'Nombre del departamento',
  edif VARCHAR(30) NOT NULL COMMENT 'Edificio donde funciona el departamento',
  presup DECIMAL(12,2) NOT NULL COMMENT 'Presupuesto anual del departamento en dólares',
  f_crea DATE COMMENT 'Fecha de creación del departamento'
) COMMENT='Departamentos académicos de la universidad';

CREATE TABLE prof (
  id_prof INT PRIMARY KEY COMMENT 'Identificador del profesor',
  nom_prof VARCHAR(50) NOT NULL COMMENT 'Nombre del profesor',
  ape_prof VARCHAR(50) NOT NULL COMMENT 'Apellido del profesor',
  email_prof VARCHAR(100) COMMENT 'Correo institucional del profesor',
  id_depto INT NOT NULL COMMENT 'Departamento al que pertenece el profesor',
  grado VARCHAR(20) NOT NULL COMMENT 'Grado académico: Doctor, Magíster o Licenciado',
  f_ing DATE NOT NULL COMMENT 'Fecha de ingreso del profesor a la universidad',
  sal DECIMAL(10,2) NOT NULL COMMENT 'Salario mensual del profesor en dólares',
  FOREIGN KEY (id_depto) REFERENCES depto(id_depto)
) COMMENT='Profesores de la universidad';

CREATE TABLE est (
  id_est INT PRIMARY KEY COMMENT 'Identificador del estudiante',
  nom_est VARCHAR(50) NOT NULL COMMENT 'Nombre del estudiante',
  ape_est VARCHAR(50) NOT NULL COMMENT 'Apellido del estudiante',
  f_nac DATE NOT NULL COMMENT 'Fecha de nacimiento del estudiante',
  gen CHAR(1) NOT NULL COMMENT 'Género del estudiante: F o M',
  email_est VARCHAR(100) COMMENT 'Correo del estudiante (puede faltar)',
  ciudad VARCHAR(50) NOT NULL COMMENT 'Ciudad de procedencia del estudiante',
  id_depto INT NOT NULL COMMENT 'Departamento de la carrera que estudia',
  f_ing DATE NOT NULL COMMENT 'Fecha de ingreso (matrícula) del estudiante',
  FOREIGN KEY (id_depto) REFERENCES depto(id_depto)
) COMMENT='Estudiantes matriculados';

CREATE TABLE crs (
  id_crs INT PRIMARY KEY COMMENT 'Identificador del curso',
  cod_crs VARCHAR(10) NOT NULL UNIQUE COMMENT 'Código del curso, ej. INF101',
  nom_crs VARCHAR(80) NOT NULL COMMENT 'Nombre del curso',
  cred TINYINT NOT NULL COMMENT 'Créditos del curso',
  niv TINYINT NOT NULL COMMENT 'Nivel o año de la carrera en que se dicta (1 a 4)',
  id_depto INT NOT NULL COMMENT 'Departamento que dicta el curso',
  FOREIGN KEY (id_depto) REFERENCES depto(id_depto)
) COMMENT='Cursos o asignaturas del catálogo';

CREATE TABLE sem (
  id_sem INT PRIMARY KEY COMMENT 'Identificador del periodo académico',
  nom_sem VARCHAR(10) NOT NULL COMMENT 'Nombre del periodo, ej. 2024-1 o 2024-V (verano)',
  anio SMALLINT NOT NULL COMMENT 'Año del periodo',
  f_ini DATE NOT NULL COMMENT 'Fecha de inicio del periodo',
  f_fin DATE NOT NULL COMMENT 'Fecha de término del periodo'
) COMMENT='Semestres y periodos de verano';

CREATE TABLE secc (
  id_secc INT PRIMARY KEY COMMENT 'Identificador de la sección (curso dictado en un periodo)',
  id_crs INT NOT NULL COMMENT 'Curso que se dicta',
  id_sem INT NOT NULL COMMENT 'Periodo en que se dicta',
  id_prof INT NOT NULL COMMENT 'Profesor a cargo de la sección',
  aula VARCHAR(10) NOT NULL COMMENT 'Sala de clases',
  cupo SMALLINT NOT NULL COMMENT 'Cupo máximo de estudiantes',
  FOREIGN KEY (id_crs) REFERENCES crs(id_crs),
  FOREIGN KEY (id_sem) REFERENCES sem(id_sem),
  FOREIGN KEY (id_prof) REFERENCES prof(id_prof)
) COMMENT='Secciones: un curso dictado por un profesor en un periodo';

CREATE TABLE insc (
  id_insc INT PRIMARY KEY COMMENT 'Identificador de la inscripción',
  id_est INT NOT NULL COMMENT 'Estudiante inscrito',
  id_secc INT NOT NULL COMMENT 'Sección en la que se inscribe',
  f_insc DATE NOT NULL COMMENT 'Fecha de inscripción',
  nota_fin DECIMAL(3,1) COMMENT 'Nota final en escala 1.0 a 7.0; NULL si está en curso o se retiró',
  est_insc VARCHAR(12) NOT NULL COMMENT 'Estado: aprobado, reprobado, retirado o en curso',
  FOREIGN KEY (id_est) REFERENCES est(id_est),
  FOREIGN KEY (id_secc) REFERENCES secc(id_secc)
) COMMENT='Inscripciones de estudiantes en secciones y su nota final';

