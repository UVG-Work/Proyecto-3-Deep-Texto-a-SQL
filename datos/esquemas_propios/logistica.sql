CREATE TABLE hub (
  hub_id INT PRIMARY KEY COMMENT 'Identificador del centro de distribución',
  hub_nm VARCHAR(60) NOT NULL COMMENT 'Nombre del centro de distribución',
  city VARCHAR(40) NOT NULL COMMENT 'Ciudad donde se ubica',
  ctry_cd CHAR(2) NOT NULL COMMENT 'País: CL=Chile, PE=Perú, AR=Argentina',
  cap_pkg_day INT NOT NULL COMMENT 'Capacidad de procesamiento en paquetes por día',
  open_dt DATE NOT NULL COMMENT 'Fecha de apertura del centro'
) COMMENT='Centros de distribución (hubs) de la empresa de envíos';

CREATE TABLE cust (
  cust_id INT PRIMARY KEY COMMENT 'Identificador del cliente',
  cust_nm VARCHAR(80) NOT NULL COMMENT 'Nombre o razón social del cliente',
  cust_typ CHAR(4) NOT NULL COMMENT 'Tipo de cliente: IND=persona natural, CORP=empresa',
  email VARCHAR(100) COMMENT 'Correo de contacto; NULL si no se registró',
  city VARCHAR(40) NOT NULL COMMENT 'Ciudad del cliente',
  reg_dt DATE NOT NULL COMMENT 'Fecha de registro del cliente'
) COMMENT='Clientes que contratan envíos';

CREATE TABLE drv (
  drv_id INT PRIMARY KEY COMMENT 'Identificador del conductor',
  fname VARCHAR(40) NOT NULL COMMENT 'Nombre de pila del conductor',
  lname VARCHAR(40) NOT NULL COMMENT 'Apellido del conductor',
  lic_cls CHAR(2) NOT NULL COMMENT 'Clase de licencia: A2=furgón, A4=camión simple, A5=camión articulado, C=motocicleta',
  hire_dt DATE NOT NULL COMMENT 'Fecha de contratación',
  home_hub_id INT NOT NULL COMMENT 'Centro de distribución base del conductor',
  sts CHAR(3) NOT NULL COMMENT 'Estado del conductor: ACT=activo, VAC=de vacaciones, INA=inactivo',
  FOREIGN KEY (home_hub_id) REFERENCES hub(hub_id)
) COMMENT='Conductores de la flota';

CREATE TABLE veh (
  veh_id INT PRIMARY KEY COMMENT 'Identificador del vehículo',
  plate_no VARCHAR(10) NOT NULL COMMENT 'Patente del vehículo',
  veh_typ CHAR(4) NOT NULL COMMENT 'Tipo de vehículo: VAN=furgón, TRK=camión, MOTO=motocicleta',
  max_wt_kg DECIMAL(8,2) NOT NULL COMMENT 'Carga máxima en kilogramos',
  hub_id INT NOT NULL COMMENT 'Centro de distribución al que está asignado',
  yr INT NOT NULL COMMENT 'Año de fabricación',
  FOREIGN KEY (hub_id) REFERENCES hub(hub_id)
) COMMENT='Vehículos de la flota';

CREATE TABLE shp (
  shp_id INT PRIMARY KEY COMMENT 'Identificador del envío',
  cust_id INT NOT NULL COMMENT 'Cliente que contrata el envío',
  orig_hub_id INT NOT NULL COMMENT 'Centro de distribución de origen',
  dest_hub_id INT NOT NULL COMMENT 'Centro de distribución de destino',
  drv_id INT COMMENT 'Conductor asignado; NULL si aún no se asigna',
  veh_id INT COMMENT 'Vehículo asignado; NULL si aún no se asigna',
  shp_dt DATETIME NOT NULL COMMENT 'Fecha y hora de despacho (creación del envío)',
  prom_dt DATE NOT NULL COMMENT 'Fecha de entrega comprometida',
  dlv_dt DATETIME COMMENT 'Fecha y hora real de entrega; NULL si no se ha entregado',
  svc_lvl CHAR(3) NOT NULL COMMENT 'Nivel de servicio: EXP=express, STD=estándar, ECO=económico',
  sts CHAR(3) NOT NULL COMMENT 'Estado: DEL=entregado, TRN=en tránsito, PND=pendiente de retiro, RET=devuelto, CAN=cancelado',
  fee_amt DECIMAL(10,2) NOT NULL COMMENT 'Tarifa cobrada por el envío completo (USD)',
  FOREIGN KEY (cust_id) REFERENCES cust(cust_id),
  FOREIGN KEY (orig_hub_id) REFERENCES hub(hub_id),
  FOREIGN KEY (dest_hub_id) REFERENCES hub(hub_id),
  FOREIGN KEY (drv_id) REFERENCES drv(drv_id),
  FOREIGN KEY (veh_id) REFERENCES veh(veh_id)
) COMMENT='Envíos (cabecera); cada envío puede contener varios paquetes';

CREATE TABLE pkg (
  pkg_id INT PRIMARY KEY COMMENT 'Identificador del paquete',
  shp_id INT NOT NULL COMMENT 'Envío al que pertenece el paquete',
  wt_kg DECIMAL(7,2) NOT NULL COMMENT 'Peso del paquete en kilogramos',
  len_cm INT NOT NULL COMMENT 'Largo en centímetros',
  wid_cm INT NOT NULL COMMENT 'Ancho en centímetros',
  hgt_cm INT NOT NULL COMMENT 'Alto en centímetros',
  decl_val_amt DECIMAL(10,2) COMMENT 'Valor declarado del contenido (USD); NULL si no se declaró',
  frag_flg TINYINT NOT NULL COMMENT 'Frágil: 1=sí, 0=no',
  FOREIGN KEY (shp_id) REFERENCES shp(shp_id)
) COMMENT='Paquetes (detalle) que componen cada envío';

CREATE TABLE trk_evt (
  evt_id INT PRIMARY KEY COMMENT 'Identificador del evento de seguimiento',
  shp_id INT NOT NULL COMMENT 'Envío al que corresponde el evento',
  hub_id INT COMMENT 'Centro de distribución donde ocurrió; NULL si ocurrió en ruta',
  evt_ts DATETIME NOT NULL COMMENT 'Fecha y hora del evento',
  evt_cd CHAR(3) NOT NULL COMMENT 'Código de evento: PU=retirado, ARR=llegada a hub, DEP=salida de hub, OFD=en reparto, DLV=entregado, EXC=incidencia, RTN=devuelto al remitente',
  note VARCHAR(120) COMMENT 'Observación del evento; NULL si no hay',
  FOREIGN KEY (shp_id) REFERENCES shp(shp_id),
  FOREIGN KEY (hub_id) REFERENCES hub(hub_id)
) COMMENT='Eventos de seguimiento (tracking) de los envíos';

