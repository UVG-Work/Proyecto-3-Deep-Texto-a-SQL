CREATE TABLE users (
  user_id INT PRIMARY KEY COMMENT 'Identificador del usuario',
  username VARCHAR(40) NOT NULL UNIQUE COMMENT 'Nombre de usuario público',
  email VARCHAR(100) NOT NULL COMMENT 'Correo electrónico',
  country VARCHAR(40) NOT NULL COMMENT 'País del usuario',
  birth_date DATE COMMENT 'Fecha de nacimiento; puede faltar',
  signup_date DATE NOT NULL COMMENT 'Fecha de registro en la plataforma',
  subscription_type VARCHAR(10) NOT NULL COMMENT 'Plan: free, premium o family',
  premium_since DATE COMMENT 'Fecha desde la que paga suscripción; NULL en plan free'
) COMMENT='Usuarios de la plataforma de streaming';

CREATE TABLE artists (
  artist_id INT PRIMARY KEY COMMENT 'Identificador del artista',
  name VARCHAR(80) NOT NULL COMMENT 'Nombre artístico',
  country VARCHAR(40) COMMENT 'País de origen',
  genre VARCHAR(30) NOT NULL COMMENT 'Género musical principal',
  debut_year INT COMMENT 'Año de debut',
  monthly_listeners INT NOT NULL DEFAULT 0 COMMENT 'Oyentes mensuales'
) COMMENT='Artistas y bandas';

CREATE TABLE albums (
  album_id INT PRIMARY KEY COMMENT 'Identificador del álbum',
  artist_id INT NOT NULL COMMENT 'Artista dueño del álbum',
  title VARCHAR(100) NOT NULL COMMENT 'Título del álbum',
  release_date DATE NOT NULL COMMENT 'Fecha de lanzamiento',
  album_type VARCHAR(10) NOT NULL COMMENT 'Formato: album, ep o single',
  record_label VARCHAR(60) COMMENT 'Sello discográfico; NULL si es independiente',
  FOREIGN KEY (artist_id) REFERENCES artists(artist_id)
) COMMENT='Álbumes, EPs y sencillos';

CREATE TABLE tracks (
  track_id INT PRIMARY KEY COMMENT 'Identificador de la canción',
  album_id INT NOT NULL COMMENT 'Álbum al que pertenece',
  title VARCHAR(100) NOT NULL COMMENT 'Título de la canción',
  track_number INT NOT NULL COMMENT 'Número de pista dentro del álbum',
  duration_seconds INT NOT NULL COMMENT 'Duración en segundos',
  explicit TINYINT(1) NOT NULL DEFAULT 0 COMMENT '1 si tiene contenido explícito',
  popularity INT NOT NULL COMMENT 'Índice de popularidad de 0 a 100',
  FOREIGN KEY (album_id) REFERENCES albums(album_id)
) COMMENT='Canciones';

CREATE TABLE playlists (
  playlist_id INT PRIMARY KEY COMMENT 'Identificador de la playlist',
  user_id INT NOT NULL COMMENT 'Usuario creador',
  name VARCHAR(80) NOT NULL COMMENT 'Nombre de la playlist',
  created_at DATETIME NOT NULL COMMENT 'Fecha y hora de creación',
  is_public TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1 si es pública, 0 si es privada',
  FOREIGN KEY (user_id) REFERENCES users(user_id)
) COMMENT='Listas de reproducción creadas por usuarios';

CREATE TABLE playlist_tracks (
  playlist_id INT NOT NULL COMMENT 'Playlist',
  track_id INT NOT NULL COMMENT 'Canción incluida',
  position INT NOT NULL COMMENT 'Posición de la canción en la playlist',
  added_at DATETIME NOT NULL COMMENT 'Fecha y hora en que se agregó',
  PRIMARY KEY (playlist_id, track_id),
  FOREIGN KEY (playlist_id) REFERENCES playlists(playlist_id),
  FOREIGN KEY (track_id) REFERENCES tracks(track_id)
) COMMENT='Canciones contenidas en cada playlist';

CREATE TABLE plays (
  play_id INT PRIMARY KEY COMMENT 'Identificador de la reproducción',
  user_id INT NOT NULL COMMENT 'Usuario que reprodujo',
  track_id INT NOT NULL COMMENT 'Canción reproducida',
  played_at DATETIME NOT NULL COMMENT 'Fecha y hora de inicio de la reproducción',
  seconds_played INT NOT NULL COMMENT 'Segundos efectivamente escuchados',
  device VARCHAR(20) NOT NULL COMMENT 'Dispositivo: mobile, desktop, web o smart_speaker',
  FOREIGN KEY (user_id) REFERENCES users(user_id),
  FOREIGN KEY (track_id) REFERENCES tracks(track_id)
) COMMENT='Historial de reproducciones';

