-- Esquema hospital: gestión hospitalaria con nombres en inglés

CREATE TABLE departments (
  department_id INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador del departamento',
  name VARCHAR(60) NOT NULL COMMENT 'Nombre del departamento (en inglés, p. ej. Cardiology)',
  floor TINYINT NOT NULL COMMENT 'Planta del edificio donde se ubica (0 = planta baja)',
  phone VARCHAR(15) NULL COMMENT 'Teléfono interno del departamento',
  PRIMARY KEY (department_id)
) COMMENT='Departamentos o servicios del hospital';

CREATE TABLE doctors (
  doctor_id INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador del médico',
  first_name VARCHAR(50) NOT NULL COMMENT 'Nombre del médico',
  last_name VARCHAR(60) NOT NULL COMMENT 'Apellido del médico',
  specialty VARCHAR(60) NOT NULL COMMENT 'Especialidad médica (en inglés)',
  department_id INT NOT NULL COMMENT 'Departamento al que está asignado',
  hire_date DATE NOT NULL COMMENT 'Fecha de contratación',
  salary DECIMAL(10,2) NOT NULL COMMENT 'Salario mensual bruto en euros',
  email VARCHAR(120) NOT NULL COMMENT 'Correo corporativo',
  license_number VARCHAR(20) NULL COMMENT 'Número de colegiado (NULL si está en trámite)',
  PRIMARY KEY (doctor_id),
  CONSTRAINT fk_doc_dep FOREIGN KEY (department_id) REFERENCES departments (department_id)
) COMMENT='Médicos del hospital';

CREATE TABLE patients (
  patient_id INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador del paciente',
  first_name VARCHAR(50) NOT NULL COMMENT 'Nombre del paciente',
  last_name VARCHAR(60) NOT NULL COMMENT 'Apellido del paciente',
  birth_date DATE NOT NULL COMMENT 'Fecha de nacimiento',
  gender CHAR(1) NOT NULL COMMENT 'Sexo: F = femenino, M = masculino',
  city VARCHAR(60) NOT NULL COMMENT 'Ciudad de residencia',
  blood_type VARCHAR(3) NOT NULL COMMENT 'Grupo sanguíneo (O+, A-, AB+...)',
  insurance_provider VARCHAR(40) NULL COMMENT 'Aseguradora médica privada (NULL = sin seguro privado)',
  registered_on DATE NOT NULL COMMENT 'Fecha de alta del paciente en el sistema',
  PRIMARY KEY (patient_id)
) COMMENT='Pacientes registrados';

CREATE TABLE appointments (
  appointment_id INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador de la cita',
  patient_id INT NOT NULL COMMENT 'Paciente citado',
  doctor_id INT NOT NULL COMMENT 'Médico que atiende la cita',
  appointment_datetime DATETIME NOT NULL COMMENT 'Fecha y hora de la cita',
  status VARCHAR(15) NOT NULL COMMENT 'Estado: scheduled (programada), completed (realizada), cancelled (cancelada), no_show (el paciente no acudió)',
  reason VARCHAR(100) NOT NULL COMMENT 'Motivo de la consulta (en inglés)',
  fee DECIMAL(8,2) NULL COMMENT 'Importe cobrado por la consulta en euros (NULL si aún no se ha realizado)',
  PRIMARY KEY (appointment_id),
  CONSTRAINT fk_app_pat FOREIGN KEY (patient_id) REFERENCES patients (patient_id),
  CONSTRAINT fk_app_doc FOREIGN KEY (doctor_id) REFERENCES doctors (doctor_id)
) COMMENT='Citas médicas';

CREATE TABLE diagnoses (
  diagnosis_id INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador del diagnóstico',
  appointment_id INT NOT NULL COMMENT 'Cita en la que se emitió el diagnóstico',
  icd_code VARCHAR(10) NOT NULL COMMENT 'Código CIE-10 (ICD-10) de la enfermedad',
  description VARCHAR(120) NOT NULL COMMENT 'Descripción de la enfermedad (en inglés)',
  severity VARCHAR(10) NOT NULL COMMENT 'Gravedad: mild (leve), moderate (moderada), severe (grave)',
  PRIMARY KEY (diagnosis_id),
  CONSTRAINT fk_diag_app FOREIGN KEY (appointment_id) REFERENCES appointments (appointment_id)
) COMMENT='Diagnósticos emitidos en las citas';

CREATE TABLE medications (
  medication_id INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador del medicamento',
  name VARCHAR(80) NOT NULL COMMENT 'Nombre comercial y dosis del medicamento',
  unit_price DECIMAL(8,2) NOT NULL COMMENT 'Precio por envase en euros',
  manufacturer VARCHAR(60) NOT NULL COMMENT 'Laboratorio fabricante',
  PRIMARY KEY (medication_id)
) COMMENT='Catálogo de medicamentos';

CREATE TABLE prescriptions (
  prescription_id INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador de la receta',
  diagnosis_id INT NOT NULL COMMENT 'Diagnóstico que motiva la receta',
  medication_id INT NOT NULL COMMENT 'Medicamento recetado',
  dosage VARCHAR(30) NOT NULL COMMENT 'Pauta de administración (en inglés)',
  duration_days INT NOT NULL COMMENT 'Duración del tratamiento en días',
  quantity INT NOT NULL COMMENT 'Número de envases recetados',
  PRIMARY KEY (prescription_id),
  CONSTRAINT fk_rx_diag FOREIGN KEY (diagnosis_id) REFERENCES diagnoses (diagnosis_id),
  CONSTRAINT fk_rx_med FOREIGN KEY (medication_id) REFERENCES medications (medication_id)
) COMMENT='Recetas de medicamentos asociadas a diagnósticos';

CREATE TABLE admissions (
  admission_id INT NOT NULL AUTO_INCREMENT COMMENT 'Identificador del ingreso hospitalario',
  patient_id INT NOT NULL COMMENT 'Paciente ingresado',
  department_id INT NOT NULL COMMENT 'Departamento donde ingresa',
  admission_date DATE NOT NULL COMMENT 'Fecha de ingreso',
  discharge_date DATE NULL COMMENT 'Fecha de alta (NULL si sigue ingresado)',
  room_number VARCHAR(6) NOT NULL COMMENT 'Número de habitación',
  total_cost DECIMAL(10,2) NULL COMMENT 'Coste total de la estancia en euros (NULL hasta el alta)',
  PRIMARY KEY (admission_id),
  CONSTRAINT fk_adm_pat FOREIGN KEY (patient_id) REFERENCES patients (patient_id),
  CONSTRAINT fk_adm_dep FOREIGN KEY (department_id) REFERENCES departments (department_id)
) COMMENT='Ingresos (hospitalizaciones) de pacientes';

